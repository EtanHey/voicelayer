#!/usr/bin/env python3
import argparse
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parent.parent
# These are separate formal/replay or opt-in artifact gates, not silent release skips.
DEFERRED = {
 'testTLCF5CaptureProjectionDrivesRealRouterAndState': 'formal/speech-queue/check.sh; VOICELAYER_F5_CASES and VOICELAYER_F5_WIRE',
 'testRealDaemonSettlementFramesProjectResumedReadToSpeaking': 'formal/speech-queue/check.sh; VOICELAYER_F5_DAEMON_WIRE',
 'testCloneShortChunkedDaemonFramesResumeAtPausedWord': 'F-resume-clone runtime; VOICELAYER_F5_CLONE_WIRE',
 'testWritesTheAddAndOpenedSheetsInLightAndDark': 'opt-in screenshot regeneration',
 'testSpeechHistoryLoadingPresentation': 'opt-in screenshot regeneration',
 'testSpeechHistoryPresentationInLightAndDark': 'opt-in screenshot regeneration',
}
def generate():
    rows=[]
    for spec in json.loads((ROOT/'tests/fixtures/e2e-2.4/coverage-spec.json').read_text()):
        source=ROOT/spec['source']
        names=re.findall(r'func (test\w+)\(',source.read_text())
        cls=source.stem
        rows.append(dict(**spec,cases=[cls+'/'+n for n in names if n not in DEFERRED],
                         deferred={cls+'/'+n:DEFERRED[n] for n in names if n in DEFERRED},kind='unit/offscreen'))
    return rows
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'tests/fixtures/e2e-2.4/coverage.json'
    text=json.dumps(generate(),indent=2)+'\n'
    if a.check:
        if path.read_text()!=text: raise SystemExit('coverage drift: run python3 scripts/generate-e2e-2.4-coverage.py')
    else: path.write_text(text)
    import importlib.util
    spec=importlib.util.spec_from_file_location('gate',ROOT/'scripts/e2e-2.4.py')
    gate=importlib.util.module_from_spec(spec);spec.loader.exec_module(gate)
    lines=['# 2.4 flow coverage', '', 'Generated by `python3 scripts/generate-e2e-2.4-coverage.py`. Inventory is not execution proof.', '', '| Flow | Source case class | Kind |', '|---|---|---|']
    for row in generate():
        lines.append('| '+row['flow']+' | '+Path(row['source']).stem+' ('+str(len(row['cases']))+' exact methods) | unit/offscreen |')
    lines += ['', '| Native flow | Required ledger surfaces | Owner |', '|---|---|---|']
    for flow,(owner,surfaces) in gate.NATIVE_CASES.items():
        lines.append('| '+flow+' | '+(', '.join('e2e24:'+s for s in surfaces) or 'UNPROVED-native, no case')+' | '+owner+' |')
    lines += ['', 'The formal History replay runs in `formal/speech-queue/check.sh`, not the isolated gate.', '', '| Separate case | Reason / M1 clearance |', '|---|---|']
    for name,reason in DEFERRED.items(): lines.append('| '+name+' | '+reason+'; can clear on M1 with producer/opt-in flag |')
    markdown='\n'.join(lines)+'\n'
    doc=ROOT/'docs/e2e-2.4-coverage.md'
    if a.check:
        if doc.read_text()!=markdown: raise SystemExit('coverage Markdown drift')
    else: doc.write_text(markdown)
