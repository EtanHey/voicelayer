    private static func normalizeRecentTranscriptions(_ items: [String]) -> [String] {
        var unique: [String] = []
        for raw in items {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, !unique.contains(trimmed) else { continue }
            unique.append(trimmed)
            if unique.count == maxRecentTranscriptions {
                break
            }
        }
        return unique
    }

    private static func normalizeRecentTranscriptionEntries(
        _ entries: [RecentTranscriptionEntry],
        fallbackTexts: [String] = []
    ) -> [RecentTranscriptionEntry] {
        let sourceEntries = entries.isEmpty
            ? normalizeRecentTranscriptions(fallbackTexts).map { RecentTranscriptionEntry(text: $0) }
            : entries
        var unique: [RecentTranscriptionEntry] = []
        var seenKeys = Set<String>()
        for entry in sourceEntries {
            let text = entry.text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !text.isEmpty else { continue }
            let path = entry.recordingPath?.trimmingCharacters(in: .whitespacesAndNewlines)
            let normalizedPath = path?.isEmpty == false ? path : nil
            let key = normalizedPath ?? text
            guard !seenKeys.contains(key) else { continue }
            seenKeys.insert(key)
            unique.append(RecentTranscriptionEntry(
                text: text,
                recordingPath: normalizedPath,
                dictationReceipt: entry.dictationReceipt,
                createdAt: entry.createdAt,
                deliveryNote: entry.deliveryNote
            ))
            if unique.count == maxRecentTranscriptions {
                break
            }
        }
        return unique
    }

    private static func normalizeVocabularyTerms(_ items: [String]) -> [String] {
        var unique: [String] = []
        for raw in items {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, !unique.contains(trimmed) else { continue }
            unique.append(trimmed)
            if unique.count == maxVocabularyTerms {
                break
            }
        }
        return unique
    }

    private static func normalizeVocabularyAliases(
        _ items: [STTVocabularyAliasPreview]
    ) -> [STTVocabularyAliasPreview] {
        var unique: [STTVocabularyAliasPreview] = []
        for item in items {
            let from = item.from.trimmingCharacters(in: .whitespacesAndNewlines)
            let to = item.to.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !from.isEmpty, !to.isEmpty else { continue }
            let normalized = STTVocabularyAliasPreview(from: from, to: to)
            guard !unique.contains(normalized) else { continue }
            unique.append(normalized)
            if unique.count == maxVocabularyAliases {
                break
            }
        }
        return unique
    }

