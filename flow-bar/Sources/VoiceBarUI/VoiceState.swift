    private static func clipboardTextRefusal(_ text: String) -> String? {
        guard text.utf16.count <= 200_000 else { return "Clipboard text is too long" }
        // Match JS.trim in parseCommand; Swift whitespace categories also include other scalars.
        let nonblank = text.unicodeScalars.contains {
            switch $0.value {
            case 0x0009...0x000D, 0x0020, 0x00A0, 0x1680, 0x2000...0x200A,
                 0x2028, 0x2029, 0x202F, 0x205F, 0x3000, 0xFEFF: return false
            default: return true
            }
        }
        return nonblank ? nil : "Clipboard has no text"
    }

    private func speakCapturedText(fromClipboard: Bool) {
        if let reason = VoiceBarPresentation.selectionBusyReason(mode: mode, hotkeyPhase: hotkeyPhase) {
            showSelectionBusyNote()
            logDiagnostic("selection_busy", details: ["reason": reason.rawValue, "appKeyWindowTitle": "not_recorded"])
            return
        }
        guard !selectionCaptureInFlight else {
            selectionCaptureCancelled = true
            if mode == .speaking || selectionSubmittedText != nil { stopSelectionRead() }
            return
        }
        guard mode != .disconnected, sendCommand != nil, !fromClipboard || isConnected else {
            showConfirmation("VoiceLayer is disconnected")
            return
        }
        // QUEUE1: reads F5 left waiting count as live, so an empty press clears them like Stop.
        let replacing = mode == .speaking || selectionSubmittedText != nil || readQueueCurrentRequestID != nil
        let pressPlaybackText = selectionReadText ?? (selectionReadIsPreparing || statusText.isEmpty ? nil : statusText)
        let pressText = selectionSubmittedText ?? pressPlaybackText
        let pressHash = selectionSubmittedText == nil ? selectionReadHash : nil
        let speechEpoch = selectionSpeechEpoch
        let captureID = UUID()
        selectionCaptureID = captureID
        selectionCaptureInFlight = true
        selectionCaptureCancelled = false
        let isCurrent = { [weak self] in
            guard let self else { return false }
            return self.selectionCaptureID == captureID && !self.selectionCaptureCancelled
                && self.isConnected && self.sendCommand != nil && self.selectionSpeechEpoch == speechEpoch
                && self.mode != .disconnected && self.mode != .error
                && VoiceBarPresentation.selectionBusyReason(mode: self.mode, hotkeyPhase: self.hotkeyPhase) == nil
        }
        let complete: (SelectionCaptureResult) -> Void = { [weak self] result in
            guard let self, selectionCaptureID == captureID else { return }
            selectionCaptureID = nil
            logDiagnostic("selection_capture", details: result.diagnosticDetails)
            selectionCaptureInFlight = false
            guard !selectionCaptureCancelled else {
                selectionCaptureCancelled = false
                return
            }
            // Capturing yields to the run loop. A new F5 session always wins.
            guard mode != .recording, mode != .transcribing, mode != .disconnected,
                  hotkeyPhase == .idle, selectionSpeechEpoch == speechEpoch else { return }
            if fromClipboard {
                guard isConnected, sendCommand != nil else { return }
                let refusal = result.text.flatMap(Self.clipboardTextRefusal)
                guard result.outcome == .completed, result.text != nil, refusal == nil else {
                    let message = result.outcome == .secureField ? "Can't read a secure field"
                        : result.outcome == .clipboardChanged ? "Clipboard changed. Try Read Clipboard again"
                        : result.outcome == .completed ? (refusal ?? "Clipboard has no text") : "Couldn't read the clipboard safely"
                    expandFromCollapse()
                    showConfirmation(message)
                    startCollapseTimer()
                    return
                }
            }
            let normalized = Self.normalizedSelection(result.text ?? "")
            // Preparing's label is not input text. Prefer own input, otherwise use reliable
            // speaking text at completion; a same-read receipt may have arrived during capture.
            let playbackText = selectionReadText ?? (selectionReadIsPreparing || statusText.isEmpty ? nil : statusText)
            let currentText = selectionSubmittedText ?? playbackText
            // Natural completion may clear the read while capture is awaiting its result.
            // Keep that press's Stop comparison, while newer live receipts still take priority.
            let readEnded = mode == .idle && selectionSubmittedText == nil
                && selectionReadID == nil && selectionReadRequestID == nil
            let comparisonText = currentText ?? (readEnded ? pressText : nil)
            let comparisonHash = selectionReadHash ?? (readEnded ? pressHash : nil)
            let sameSelection: Bool
            if selectionSubmittedText == nil, let hash = comparisonHash {
                sameSelection = Self.selectionHash(result.text ?? "") == hash
            } else {
                sameSelection = comparisonText.map { normalized == Self.normalizedSelection($0) } ?? false
            }
            // QUEUE1: with a newer selection queued, the read playing now is still "the same selection".
            let samePlaying = selectionSubmittedText != nil && (selectionReadHash.map {
                Self.selectionHash(result.text ?? "") == $0
            } ?? selectionReadText.map { normalized == Self.normalizedSelection($0) } ?? false)
            if !fromClipboard, !normalized.isEmpty, !selectionQueueSnapshotIsEmpty {
                let first = selectionSpeechRequestID != nil && readQueueCurrentRequestID == nil && selectionReadRequestID == nil
                    ? selectionSubmissions.min(by: { $0.value.order < $1.value.order }) : nil
                let owner = selectionReadRequestID ?? readQueueCurrentRequestID ?? first?.key
                let pending = selectionSubmissions.filter { $0.key != owner }.map { $0.value.text }
                // A paused read is still the read on screen: the same text dedupes against it too.
                let playing = mode == .idle && readQueueCurrentRequestID != nil ? nil
                    : selectionReadText ?? first?.value.text
                        ?? (samePlaying || (selectionSubmittedText == nil && sameSelection) ? result.text
                            : playbackText ?? (readEnded ? pressPlaybackText : nil))
                switch SelectionAdmission.decide(result.text ?? "", playing: playing, pending: pending,
                                                count: selectionReadText == nil && first == nil ? readQueueCount : max(readQueueCount, pending.count)) {
                case .advance:
                    if let owner {
                        clearCurrentSelectionReadIdentity()
                        retireSelectionRequest(owner)
                        sendCommand?(["cmd": "read_next", "request_id": owner])
                    }
                    return
                case .stop: stopSelectionRead(); return
                case .alreadyQueued: showSelectionBusyNote(message: "Already queued"); return
                case .alreadyReading: showSelectionBusyNote(message: Self.alreadyReadingNote); return
                case .submit: break
                }
            }
            // Etan, 2026-11-08 4:40 pm, Option+F5 over a read that is playing or paused:
            // an empty selection pauses it (or resumes it when paused); the same text dedupes with a notice and keeps
            // its position; different text joins the narration queue (below, `queue: true`).
            // A capture that FAILED (copy timed out, secure field...) is not an empty selection: it keeps its old rule.
            // A selection's same-text dedupe is the daemon's (it knows the read's identity, and answers "Already
            // reading this"); Swift decides it only for a clipboard read, which the daemon would start afresh.
            let readOnScreen = mode == .speaking
            let emptySelection = result.outcome == .nothingSelected || result.outcome == .copyEmpty
                || (result.outcome == .completed && normalized.isEmpty)
            if replacing, readOnScreen, !fromClipboard, normalized.isEmpty, emptySelection {
                togglePlaybackPause()
                return
            }
            if replacing, readOnScreen, fromClipboard, sameSelection || samePlaying {
                showSelectionBusyNote(message: Self.alreadyReadingNote)
                return
            }
            if replacing, (!fromClipboard && normalized.isEmpty) || (fromClipboard && (sameSelection || samePlaying)) {
                stopSelectionRead()
                return
            }
            guard let text = result.text, fromClipboard ? !text.isEmpty : !normalized.isEmpty else {
                expandFromCollapse()
                switch result.outcome {
                case .secureField: showConfirmation("Can't read a secure field")
                case .clipboardRestoreFailed: showConfirmation("Couldn't restore the clipboard")
                case .clipboardChanged: showConfirmation(SelectionErrorFeedback.clipboardChanged)
                case .nothingSelected: showConfirmation(SelectionErrorFeedback.nothingSelected)
                case .copyTimedOut: showConfirmation(SelectionErrorFeedback.copyTimedOut)
                case .copyEmpty: showConfirmation(SelectionErrorFeedback.copyEmpty)
                case .copyFailed: showConfirmation(SelectionErrorFeedback.copyFailed)
                case .captureFailed: showConfirmation("Couldn't read the selection, try again")
                case .completed: showConfirmation("No text selected")
                }
                startCollapseTimer()
                return
            }
            if replacing, readQueueCount >= Self.readQueueLimit {
                showSelectionBusyNote(message: "Queue full")
                return
            }
            let requestID = UUID().uuidString
            selectionSpeechRequestID = requestID
            selectionSubmittedText = text
            selectionSubmissionOrder += 1
            selectionSubmissions[requestID] = (text, selectionSubmissionOrder)
            selectionUnacknowledgedRequestIDs.insert(requestID)
            if selectionSubmissions.count > Self.selectionIdentityLimit,
               let oldest = selectionSubmissions.min(by: { $0.value.order < $1.value.order })?.key {
                // Forget only the text: an unresolved request may still receive a valid receipt.
                selectionUnacknowledgedRequestIDs.remove(oldest)
                selectionSubmissions.removeValue(forKey: oldest)
            }
            // speak_text preempts only the owned read and awaits its player teardown (PLAYER0/FX).
            // QUEUE1 (Etan, 2026-10-20): a different selection while reading queues behind it; the daemon starts
            // it at once when no Option+F5 read is live. speak_text otherwise preempts only the owned read.
            var command: [String: Any] = ["cmd": "speak_text", "id": requestID, "text": text, "profile": "auto",
                                          "format": fromClipboard ? "plain" : "markdown",
                                          "source": fromClipboard ? "clipboard" : "selection",
                                          "text_hash": Self.selectionHash(text)]
            if !fromClipboard, result.path == .ax || result.path == .copy {
                command["capture_path"] = result.path.rawValue
            }
            // The existing queue route also owns the first explicit clipboard read, without claiming AX selection.
            if replacing || fromClipboard { command["queue"] = true }
            sendCommand?(command)
        }
        if fromClipboard { clipboardTextReadHandler(isCurrent, complete) }
        else { selectionTextCaptureHandler(complete) }
    }

