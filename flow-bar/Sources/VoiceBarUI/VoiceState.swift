    private func handleAckEvent(_ event: [String: Any]) {
        let updateBusy = event["outcome"] as? String == "reject"
            && (event["reason"] as? String)?.hasPrefix("UPDATE_BUSY") == true
        defer { if updateBusy { showConfirmation(NativeUpdateGate.busyMessage) } }
        if let command = event["command"] as? String, command == "pause" || command == "resume" {
            handlePlaybackPauseAck(event, command: command)
            return
        }
        if event["command"] as? String == "speech_seek" {
            if event["reason"] as? String == "word timing unavailable" { reportWordTimingUnavailable() }
            return
        }
        if event["command"] as? String == "seek" {
            guard let id = event["id"] as? String, pendingReadbackSeekIDs.remove(id) != nil else { return }
            if event["outcome"] as? String != "accept", isTeleprompterReadback {
                showConfirmation(event["reason"] as? String ?? "Seek failed")
            }
            return
        }
        // speak_text is not a recorder intent. Match its raw ack without changing that contract.
        if event["command"] as? String == "speak_text" {
            guard let id = event["id"] as? String, selectionSubmissions[id] != nil else { return }
            selectionUnacknowledgedRequestIDs.remove(id)
            if ["selection advanced", "Already queued", Self.alreadyReadingNote].contains(event["reason"] as? String ?? "") {
                retireSelectionRequest(id)
                if selectionSpeechRequestID == id {
                    selectionSpeechRequestID = nil
                    selectionSubmittedText = nil
                }
                if event["reason"] as? String == "Already queued" { showSelectionBusyNote(message: "Already queued") }
                if event["reason"] as? String == Self.alreadyReadingNote { showSelectionBusyNote(message: Self.alreadyReadingNote) }
            }
            if event["outcome"] as? String == "reject" {
                retireSelectionRequest(id)
                if selectionReadRequestID == id { clearCurrentSelectionReadIdentity() }
                if selectionSpeechRequestID == id {
                    selectionSpeechRequestID = nil
                    selectionSubmittedText = nil
                }
                let reason = event["reason"] as? String
                showSelectionBusyNote(message: reason == "busy" ? "Busy. Selection not read"
                    : reason == "queue full" ? "Queue full" : "Selection not read. Try again")
                logDiagnostic("selection_rejected", details: ["outcome": "reject", "appKeyWindowTitle": "not_recorded"])
            }
            return
        }
        guard let ack = SocketAckEvent(event: event) else {
            return
        }

        onAckEvent?(ack)

        if ack.command == .setWhisperEffort {
            handleEffortAck(ack, event: event)
            return
        }

        if ack.command == .setTTSSetting || ack.command == .previewTTSProfile {
            handleSpeechAck(ack, event: event)
            return
        }
        if ack.command == .setProcessingSetting {
            handleProcessingAck(ack, event: event)
            return
        }

        if ack.command == .setWhisperResidency,
           ack.id == pendingResidencyID || ack.id == timedOutResidencyID {
            if ack.outcome == .loading {
                if ack.id == pendingResidencyID {
                    // Two 30 s STARTUP_TIMEOUT attempts (CoreML then Metal), plus health and cleanup probes.
                    scheduleResidencyTimeout(id: ack.id, after: 75)
                }
                return
            }
            pendingResidencyID = nil
            timedOutResidencyID = nil
            pendingResidencyTarget = nil
            pendingResidencyTimeout?.cancel()
            pendingResidencyTimeout = nil
            residencyNotice = ack.outcome == .accept ? nil : (ack.reason ?? "Could not change memory state")
            if let modelStatus = event["model_status"] as? [String: Any] {
                let fresh = ModelsSettingsState(healthEvent: [
                    "type": "health", "recording_state": "idle", "model_status": modelStatus,
                ])
                modelsSettingsState = fresh.retainingPolishControls(from: modelsSettingsState)
                refreshModelsBusy()
            } else {
                refreshModelsSettingsStatus()
            }
            return
        }

        if ack.command == .setRecordingPause,
           let pendingRecordingPause,
           pendingRecordingPause.id == ack.id {
            // A noop that says the daemon is already where we asked to be keeps the optimistic state.
            let alreadyThere = ack.outcome == .noop && (ack.reason == "already paused" || ack.reason == "not paused")
            self.pendingRecordingPause = nil
            if ack.outcome != .accept, !alreadyThere, mode == .recording {
                let previous = pendingRecordingPause.previous
                isRecordingPaused = previous.isPaused
                recordingPausedAtUptimeMs = previous.pausedAtUptimeMs
                recordingPausedTotalMs = previous.pausedTotalMs
            }
            return
        }

        if ack.command == .setRecordingHold,
           let pendingRecordingHold,
           pendingRecordingHold.id == ack.id {
            if ack.outcome != .accept {
                isRecordingHoldEngaged = pendingRecordingHold.previous
            }
            self.pendingRecordingHold = nil
            return
        }

        if ack.command == .retranscribeRecording,
           historyRetranscriptionRequest.matchesIntent(id: ack.id) {
            let path = historyRetranscriptionRequest.currentPath()
            historyRetranscriptionRequest.acknowledgeIntent()
            if ack.outcome != .accept {
                historyRetranscriptionRequest.reject(path: path)
                showConfirmation(ack.reason ?? "Nothing to transcribe")
            }
            return
        }

        guard pendingIntent?.id == ack.id,
              pendingIntent?.command == ack.command
        else {
            return
        }

        recordStartAckTimeoutTask?.cancel()
        pendingIntent = nil

        if ack.command == .retranscribeLast {
            if ack.outcome == .accept {
                // The daemon rejects retranscription while any capture is active, so acceptance is
                // authoritative that an older remote ownership latch or shadow is now stale.
                releaseRemoteCaptureOwnership(preservingPossibleTranscript: false)
            } else {
                pendingRecoveredTranscriptionPaste = false
                showConfirmation(ack.reason ?? "Nothing to transcribe")
            }
            return
        }

        if ack.command == .retranscribeRecording, ack.outcome != .accept {
            clearHistoryRetranscriptionRequest(removeSuppression: true)
            showConfirmation(ack.reason ?? "Nothing to transcribe")
            return
        }

        guard ack.command == .record, ack.outcome == .reject else { return }

        let canRecoverLateRecording = ack.reason == "VoiceLayer is starting"
        barInitiatedRecording = false
        releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
        barInitiatedTimeout?.cancel()
        recordingIdleCleanupTask?.cancel()
        recordStartAckTimeoutTask?.cancel()
        keepsPasteFlowEnvelope = false
        if canRecoverLateRecording {
            scheduleRecordStartLateRecovery()
        } else {
            clearRecordStartLateRecovery(clearPasteTarget: true)
        }
        hotkeyPhase = .idle
        resetAudioLevels()
        mode = .error
        errorMessage = ack.reason ?? "Unable to start recording"
        onModeChange?(.error)
        expandFromCollapse()
    }

    private func handleCommandModeEvent(_ event: [String: Any]) {
        guard let phaseString = event["phase"] as? String,
              let phase = CommandModePhase(rawValue: phaseString),
              let operation = event["operation"] as? String else {
            return
        }

        commandModeState = CommandModeState(
            phase: phase,
            operation: operation,
            prompt: event["prompt"] as? String
        )
        expandFromCollapse()

        guard phase == .applying, let replacementText = event["replacement_text"] as? String else {
            return
        }

        guard let commandModeApplyHandler else { return }
        let result = commandModeApplyHandler(replacementText)

        switch result {
        case let .axVerified(message):
            commandModeState = CommandModeState(phase: .done, operation: operation, prompt: event["prompt"] as? String)
            showConfirmation(message)
        case let .clipboardFallback(message):
            commandModeState = CommandModeState(
                phase: .fallback,
                operation: operation,
                prompt: event["prompt"] as? String
            )
            showConfirmation(message)
        case let .failed(message):
            commandModeState = CommandModeState(phase: .error, operation: operation, prompt: event["prompt"] as? String)
            mode = .error
            errorMessage = message
        }
    }

    private static func capturePasteboardSnapshot(pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        let items = pasteboard.pasteboardItems?.compactMap { item -> [String: Data]? in
            let values = item.types.reduce(into: [String: Data]()) { result, type in
                guard !type.rawValue.hasPrefix("dyn."),
                      !type.rawValue.hasPrefix("org.nspasteboard.")
                else {
                    return
                }
                if let data = item.data(forType: type) {
                    result[type.rawValue] = data
                }
            }
            return values.isEmpty ? nil : values
        } ?? []

        guard !items.isEmpty else { return nil }
        return PasteboardSnapshot(changeCount: pasteboard.changeCount, items: items)
    }

    private static func restorePasteboardSnapshot(_ snapshot: PasteboardSnapshot, pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = snapshot.items.map { itemSnapshot -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in itemSnapshot {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        pasteboard.writeObjects(items)
        pasteboard.setData(Data(), forType: .voiceBarTransient)
        pasteboard.setData(Data(), forType: .voiceBarAutoGenerated)
    }
