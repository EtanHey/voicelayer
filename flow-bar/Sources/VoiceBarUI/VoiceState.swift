        if advanceEpoch, selectionReadID != nil || selectionReadRequestID != nil {
            selectionSpeechEpoch += 1
        }
        selectionReadText = nil
        selectionReadHash = nil
        selectionReadRequestID = nil
        selectionReadID = nil
        selectionReadIsPreparing = false
    }

