    private func startTranscriptionTimeout() {
        transcriptionTimeoutTask?.cancel()
        let usesExtendedTimeout = barInitiatedRecording || historyRetranscriptionRequest.isPending
        let baseTimeout = usesExtendedTimeout ? barInitiatedTranscriptionTimeout : transcriptionTimeout
        let knownAudioMs = [lastCaptureDurationMs, daemonSttAudioMs].compactMap { $0 }.max()
        let timeout = Self.transcriptionWait(base: baseTimeout, captureDurationMs: knownAudioMs)
        transcriptionTimeoutTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: timeout)
            guard let self, !Task.isCancelled, mode == .transcribing else { return }
            failTranscription(message: "Transcription timed out while waiting for the result.")
        }
    }

    /// The daemon allows max(120 s, 4x decoded audio) plus a 15 s abort grace; the
    /// captured take is never shorter than the decoded slice, so 4x capture + 60 s
    /// always outlasts it. Short takes keep the base budget.
    static func transcriptionWait(base: Duration, captureDurationMs: Int?) -> Duration {
        guard let captureDurationMs, captureDurationMs > 0 else { return base }
        let scaled = Duration.milliseconds(captureDurationMs) * 4 + .seconds(60)
        return max(base, scaled)
    }

    private func enterIdleState(clearQueue: Bool) {
        isRecordingHandoffPending = false
        if clearQueue, mode == .speaking {
            let trimmed = statusText.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                retainedReadbackID = playbackReadbackID
                // An older daemon sends no retained range; its duration is the best it can say.
                // Lane B (QA 11:47 k06-31: completion showed "0:10 / 0:13" then "0:06 / 0:06"): the end state never
                // shows less than the read it just finished. A partial retained span is the seekable part, not the total.
                // A read that played to its whole total completed; one stopped earlier shows only its retained range.
                let total = playbackDurationMilliseconds ?? 0
                let completed = total > 0 && playbackElapsedMilliseconds() >= total - 250
                let readbackDuration = completed
                    ? max(playbackReadbackDurationMilliseconds ?? 0, total)
                    : playbackReadbackDurationMilliseconds ?? playbackDurationMilliseconds
                retainedPlaybackDurationMilliseconds = readbackDuration
                retainedPlaybackPositionMilliseconds = min(playbackElapsedMilliseconds(), readbackDuration ?? 0)
                retainedTeleprompterText = teleprompterText ?? statusText
                retainedTeleprompterWordBoundaries = teleprompterWordBoundaries
                retainedDisplayBlocks = teleprompterDisplayBlocks
                notifyPanelLayoutChangedIfNeeded(true)
            }
        }
        mode = .idle
        statusText = ""
        speechDetected = false
        recordingMode = nil
        silenceMode = nil
        errorMessage = nil
        transcriptionTimeoutTask?.cancel()
        transcribingStartedAt = nil
        transcribingStatusText = nil
        resetAudioLevels()
        wordBoundaries = []
        if retainedTeleprompterText == nil {
            isTeleprompterDismissed = false
        }
        if clearQueue {
            queueDepth = 0
            queueItems = []
        }
        hotkeyPhase = .idle
        onModeChange?(.idle)
        startCollapseTimer()
    }

