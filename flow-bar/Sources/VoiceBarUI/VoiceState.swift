    private func synchronizeModelsSettingsState(from oldMode: VoiceMode, to newMode: VoiceMode) {
        if Self.blocksModelsEffort(newMode) {
            modelsSettingsState = modelsSettingsState.settingBusy(
                true, reason: ModelsSettingsState.busyReason(mode: newMode)
            )
        } else if Self.blocksModelsEffort(oldMode) {
            // Session over: keep the last-known health so a dictation never flashes "Starting…"; the
            // effort controls stay locked, with a reason, until the post-dictation refresh answers.
            modelsSettingsState = isConnected ? lastKnownModelsStateWhileRefreshing() : .disconnected
        }
    }

    /// What Models shows while a health refresh is in flight: the last-known status, never a "Starting…"
    /// flash. An available state keeps its values with effort locked until the reply; an unreadable one stays
    /// "Status unreadable" (#162 review nit). Only an unknown state waits as `.loading`.
    private func lastKnownModelsStateWhileRefreshing() -> ModelsSettingsState {
        switch modelsSettingsState.availability {
        case .available:
            modelsSettingsState.settingBusy(true, reason: ModelsSettingsState.refreshingReason)
        case .unreadable:
            .unreadable
        case .loading, .disconnected:
            .loading
        }
    }

    private static func blocksModelsEffort(_ mode: VoiceMode) -> Bool {
        mode == .recording || mode == .transcribing
    }

    // MARK: - Idle collapse

    /// R0856-12: one of VoiceBar's own windows (Settings, the menu-bar popover) has keyboard focus. The pointer
    /// necessarily leaves the notch to use it, and that exit used to collapse the idle wings 2.5 s later (seen at
    /// 08:58:05 on 2026-11-02 as the wings vanishing for 1.5 s while Settings was key). While it has focus the
    /// wings stay; the ordinary idle countdown resumes when it resigns. It never expands a collapsed notch.
    public private(set) var isVoiceBarWindowFocused = false

    public func setVoiceBarWindowFocused(_ focused: Bool) {
        guard focused != isVoiceBarWindowFocused else { return }
        isVoiceBarWindowFocused = focused
        if focused {
            collapseTimer?.cancel()
        } else if mode == .idle, !isHovering, !isCollapsed {
            startCollapseTimer()
        }
    }

    /// Starts the ordinary idle grace period once the product surface exists.
    /// The initial state does not pass through `enterIdleState`, so the app
    /// delegate calls this after installing the panel.
    public func beginIdleCollapseCountdown() {
        guard mode == .idle else { return }
        startCollapseTimer()
    }

    private func startCollapseTimer() {
        guard modalInteractionDepth == 0 else { return }
        collapseTimer?.cancel()
        guard !keepsExpandedInDevState, retainedTeleprompterText == nil else {
            isCollapsed = false
            return
        }
        collapseTimer = Task { @MainActor in
            try? await Task.sleep(for: .seconds(idleCollapseDelay))
            if !Task.isCancelled, mode == .idle, !isHovering, modalInteractionDepth == 0,
               !isVoiceBarWindowFocused {
                withAnimation(.smooth(duration: 0.3)) {
                    isCollapsed = true
                }
            }
        }
    }

    private func expandFromCollapse() {
        collapseTimer?.cancel()
        withAnimation(.smooth(duration: 0.3)) {
            isCollapsed = false
        }
    }

    /// Called when hover state changes.
    public func setHovering(_ hovering: Bool) {
        isHovering = hovering
        if hovering, isCollapsed {
            withAnimation(.smooth(duration: 0.3)) {
                isCollapsed = false
            }
        }
        if !hovering, mode == .idle {
            startCollapseTimer()
        }
    }

    /// Product pointer tracking calls this only after its own 2.5-second exit
    /// grace has elapsed. Plain idle can therefore perform the one intended
    /// collapse immediately instead of paying the general idle timeout again.
    /// Retained read-back and modal/dev retention keep their own lifecycles.
    public func setHoveringFromDebouncedPointer(_ hovering: Bool) {
        if hovering {
            setHovering(true)
            return
        }

        isHovering = false
        collapseTimer?.cancel()
        guard mode == .idle,
              modalInteractionDepth == 0,
              !isVoiceBarWindowFocused,
              !keepsExpandedInDevState,
              retainedTeleprompterText == nil
        else { return }

        // Round 2 settles the clean static lifecycle only. The wing/panel
        // slide belongs to Round 3, so the debounced exit changes state
        // without introducing a new implicit transition here.
        isCollapsed = true
    }

    public func beginModalInteraction() {
        modalInteractionDepth += 1
        collapseTimer?.cancel()
        expandFromCollapse()
    }

    public func endModalInteraction() {
        modalInteractionDepth = max(0, modalInteractionDepth - 1)
        guard modalInteractionDepth == 0 else { return }
        if mode == .idle {
            isCollapsed = false
            startCollapseTimer()
        } else {
            expandFromCollapse()
        }
    }

