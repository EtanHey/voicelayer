    private func enterTranscribingMode() {
        let modeChanged = mode != .transcribing
        if mode == .recording, !recordingWaveformHistory.samples.isEmpty {
            transcribingWaveformReplayStartedAt = playbackAmplitudeClock()
        }
        mode = .transcribing
        if modeChanged || transcribingStartedAt == nil {
            transcribingStartedAt = currentDateProvider()
        }
        if modeChanged {
            transcribingStatusText = nil
        }
        statusText = ""
        localRecordingLevel = nil
        if modeChanged {
            // AIDEV-NOTE: the capture that was live has ended, so retire it and
            // its first-audio baseline here. This cannot call resetAudioLevels()
            // — transcribing replays `recordingWaveformHistory`, which that
            // clears. Without this, a daemon `recording` event arriving straight
            // after transcribing (a VAD turn, a second utterance on one ask)
            // re-enters with captureLive still true and the pill goes red before
            // the new capture exists.
            captureLive = false
            didLogFirstRecordingAudioLevel = false
            lastCaptureDurationMs = recordingStateUptimeMs.map { max(0, currentRecordingUptimeMs() - $0) }
            recordingStateUptimeMs = nil
            // A recording re-entered from here has no press of its own, so the
            // press delta must be absent rather than measured across the whole
            // transcribing gap — `msSinceRecordCommand` is the number the
            // head-cut work is read in.
            recordCommandUptimeMs = nil
        }
        refreshAudioLevel()
        startTranscriptionTimeout()
        hotkeyPhase = .idle
        logDiagnostic("state_transcribing", details: [
            "barInitiatedRecording": boolString(barInitiatedRecording),
            "capturedTargetApp": frontmostAppOnRecordStart?.bundleIdentifier ?? "nil",
            "hasCapturedInsertion": boolString(recordStartInsertionHandler != nil),
            "source": modeChanged ? "transition" : "refresh",
        ])
        if modeChanged {
            onModeChange?(.transcribing)
        }
        expandFromCollapse()
    }

    /// A result for a History request whose live state was already cleaned up. Only a nonempty final touches
    /// anything, and then only its own archive row (via `handleFinalTranscription`'s late-archive branch).
    private func handleLateArchivedTranscription(
        _ text: String, recordingPath: String, isPartial: Bool, recordingCreatedAt: Date? = nil,
        recordingIsLatest: Bool = false
    ) {
        guard !isPartial else { return }
        guard !text.isEmpty else {
            _ = historyRetranscriptionRequest.takeArchivedOrigin(for: recordingPath)
            logDiagnostic("transcription_final_archived_late_empty", details: ["hasRecordingPath": boolString(!recordingPath.isEmpty)])
            return
        }
        handleFinalTranscription(text, recordingPath: recordingPath, recordingCreatedAt: recordingCreatedAt,
                                 recordingIsLatest: recordingIsLatest)
    }

    private func handleFinalTranscription(
        _ text: String,
        recordingPath: String? = nil,
        dictationReceipt: DictationReceipt? = nil,
        recordingCreatedAt: Date? = nil,
        recordingIsLatest: Bool = false
    ) {
        let wasHistoryRetranscription = recordingPath.map { path in
            historyRetranscriptionRequest.suppressesPaste(for: path)
        } ?? false
        // Outlives request cleanup, so an archived result that arrives after an error or timeout is still recognised.
        let isArchivedResult = recordingPath.map { path in
            historyRetranscriptionRequest.takeArchivedOrigin(
                for: path.trimmingCharacters(in: .whitespacesAndNewlines)
            )
        } ?? false
        let rewritesArchivedRecording = wasHistoryRetranscription || isArchivedResult
        // AIDEV-NOTE: a History result whose request was already cleaned up belongs to no live capture. It only
        // rewrites its archive row; it must never paste, claim the last-dictation card, or end the timeouts/idle of
        // a dictation that started since (#186 review round 2: it pasted the archived text into the new target).
        if isArchivedResult, !wasHistoryRetranscription {
            rememberRecentTranscription(
                text,
                recordingPath: recordingPath,
                isArchiveRecovery: true,
                insertingWhenAbsent: recordingCreatedAt != nil,
                recordingCreatedAt: recordingCreatedAt,
                recordingIsLatest: recordingIsLatest
            )
            if let recordingPath { onHistoryArchiveChange?(recordingPath) }
            refreshTranscriptionVocabulary()
            logDiagnostic("transcription_final_archived_late", details: [
                "textLength": String(text.count),
                "hasRecordingPath": boolString(recordingPath?.isEmpty == false),
            ])
            return
        }
        transcriptionTimeoutTask?.cancel()
        transcribingStartedAt = nil
        transcribingStatusText = nil
        clearRecordStartLateRecovery(clearPasteTarget: false)
        transcript = text
        rememberRecentTranscription(
            text,
            recordingPath: recordingPath,
            dictationReceipt: rewritesArchivedRecording ? nil : dictationReceipt,
            isArchiveRecovery: rewritesArchivedRecording,
            insertingWhenAbsent: !rewritesArchivedRecording || recordingCreatedAt != nil,
            recordingCreatedAt: recordingCreatedAt,
            recordingIsLatest: recordingIsLatest
        )
        if recordingPath?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false {
            onHistoryArchiveChange?(recordingPath)
        }
        refreshTranscriptionVocabulary()
        logDiagnostic("transcription_final", details: [
            "textLength": String(text.count),
            "barInitiatedRecording": boolString(barInitiatedRecording),
            "capturedTargetApp": frontmostAppOnRecordStart?.bundleIdentifier ?? "nil",
            "hasCapturedInsertion": boolString(recordStartInsertionHandler != nil),
            "hasRecordingPath": boolString(recordingPath?.isEmpty == false),
        ])

        // AIDEV-NOTE: The effective remote-capture block is an independent second gate on top of
        // the classification fix in the "recording" handler. A remote-owned transcript belongs to
        // the blocked MCP caller; auto-pasting it leaks the answer into whatever app is frontmost
        // and strands the caller forever. Never remove this even if classification looks correct.
        let remoteCaptureBlocksPaste =
            remoteOwnedRecording || supersededRemoteTranscriptPending
        let shouldAutoPaste =
            barInitiatedRecording
                && !remoteOwnedRecording
                && !supersededRemoteTranscriptPending
                && !rewritesArchivedRecording
        let shouldPasteRecoveredTranscription =
            pendingRecoveredTranscriptionPaste
                && !remoteCaptureBlocksPaste
                && !rewritesArchivedRecording
        let normalizedRecordingPath = recordingPath?.trimmingCharacters(in: .whitespacesAndNewlines)
        let cardIsThisDictation = !rewritesArchivedRecording && !remoteCaptureBlocksPaste
            && (barInitiatedRecording || pendingRecoveredTranscriptionPaste)
            && recentTranscriptionEntries.first?.text == text.trimmingCharacters(in: .whitespacesAndNewlines)
            && recentTranscriptionEntries.first?.recordingPath == (normalizedRecordingPath?.isEmpty == false
                ? normalizedRecordingPath : nil)
        let cardOperationID = cardIsThisDictation ? UUID() : nil
        if let cardOperationID {
            lastDictationCardEntry = recentTranscriptionEntries.first
            latestDictationOperationID = cardOperationID
            latestDictationInsertionStatus = shouldAutoPaste || shouldPasteRecoveredTranscription
                ? .pending : .notInserted
        }
        pendingRecoveredTranscriptionPaste = false
        if wasHistoryRetranscription, let recordingPath {
            historyRetranscriptionRequest.finish(path: recordingPath)
        }
        pendingIdleAfterAutoPasteCompletion =
            (shouldAutoPaste || shouldPasteRecoveredTranscription) && mode == .transcribing

        if shouldAutoPaste {
            barInitiatedRecording = false
            barInitiatedTimeout?.cancel()
            recordingIdleCleanupTask?.cancel()
            pasteTranscript(
                text,
                for: resolvedPasteTarget(forRepaste: false),
                plan: .autoPaste,
                operationID: cardOperationID
            )
        } else if shouldPasteRecoveredTranscription {
            pasteTranscript(
                text,
                for: resolvedPasteTarget(forRepaste: true),
                plan: .repaste,
                operationID: cardOperationID
            )
        }

        // The remote caller's transcript has been delivered; release the ownership gate so a
        // following F5 dictation pastes normally.
        releaseRemoteCaptureOwnership(preservingPossibleTranscript: false)
    }

