    public func setRecordingHold(_ engaged: Bool) {
        guard mode == .recording, recordingMode == "vad" else { return }
        guard pendingRecordingHold == nil else { return }
        guard engaged != isRecordingHoldEngaged else { return }

        let id = UUID().uuidString
        let previous = isRecordingHoldEngaged
        isRecordingHoldEngaged = engaged
        pendingRecordingHold = (id: id, previous: previous)
        sendCommand?([
            "cmd": IntentCommand.setRecordingHold.rawValue,
            "engaged": engaged,
            "id": id,
        ])
    }

    public func replay() {
        sendIntent(command: .replay, payload: ["cmd": "replay"])
    }

    public func retranscribeLastCapture() {
        guard !pendingRecoveredTranscriptionPaste else { return }
        pendingRecoveredTranscriptionPaste = true
        sendIntent(
            command: .retranscribeLast,
            payload: ["cmd": "retranscribe_last"]
        )
    }

    public func retranscribeHistoryEntry(recordingPath: String) {
        let trimmedPath = recordingPath.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedPath.isEmpty else { return }
        let id = UUID().uuidString
        guard historyRetranscriptionRequest.begin(path: trimmedPath, intentID: id) else { return }
        sendCommand?([
            "cmd": "retranscribe_recording",
            "audio_path": trimmedPath,
            "id": id,
        ])
    }

    public func snooze() {
        switch mode {
        case .recording, .transcribing:
            sendIntent(command: .cancel, payload: ["cmd": "cancel"], trackPending: false)
        case .speaking:
            sendIntent(command: .stop, payload: ["cmd": "stop"], trackPending: false)
        default:
            break
        }
        barInitiatedRecording = false
        releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
        barInitiatedTimeout?.cancel()
        transcriptionTimeoutTask?.cancel()
        recordingIdleCleanupTask?.cancel()
        cancelDeferredFinalTranscription()
        recordStartAckTimeoutTask?.cancel()
        pendingRecordingIdleAfterFinal = false
        pendingIdleAfterAutoPasteCompletion = false
        pendingRecoveredTranscriptionPaste = false
        clearHistoryRetranscriptionRequest(removeSuppression: true)
        clearRecordStartLateRecovery(clearPasteTarget: false)
        keepsPasteFlowEnvelope = true
        transcribingStartedAt = nil
        transcribingStatusText = nil
        frontmostAppOnRecordStart = nil
        recordStartInsertionHandler = nil
        speechDetected = false
        resetAudioLevels()
        hotkeyPhase = .idle
        mode = .disconnected
        onModeChange?(.disconnected)
        collapseTimer?.cancel()
        isCollapsed = false
