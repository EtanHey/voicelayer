    // MARK: - Commands

    public func stop() {
        let shouldShowTranscribing = mode == .recording
        let shouldExitInterruptedPlayback = mode == .speaking
        var payload: [String: Any] = ["cmd": "stop"]
        if shouldExitInterruptedPlayback {
            payload["playback_elapsed_ms"] = playbackElapsedMilliseconds()
        }
        sendIntent(command: .stop, payload: payload)
        if shouldShowTranscribing {
            enterTranscribingMode()
        } else if shouldExitInterruptedPlayback {
            // The stop control lives outside the hardware core. When the
            // teleprompter shrinks under the pointer AppKit may not emit a
            // matching hover-exit event, so do not let that stale hover hold
            // the idle surface open forever.
            setHovering(false)
            queueDepth = 0
            queueItems = []
            clearRetainedTeleprompter()
            enterIdleState(clearQueue: false)
        }
    }

    public func dismissError() {
        pendingIntent = nil
        errorMessage = nil
        cancelDeferredFinalTranscription()
        pendingRecordingIdleAfterFinal = false
        pendingIdleAfterAutoPasteCompletion = false
        pendingRecoveredTranscriptionPaste = false
        clearHistoryRetranscriptionRequest(removeSuppression: true)
        clearRecordStartLateRecovery(clearPasteTarget: false)
        keepsPasteFlowEnvelope = false
        transcribingStartedAt = nil
        transcribingStatusText = nil
        frontmostAppOnRecordStart = nil
        recordStartInsertionHandler = nil
        speechDetected = false
        recordingMode = nil
        silenceMode = nil
        resetAudioLevels()

        if isConnected {
            mode = .idle
            onModeChange?(.idle)
            startCollapseTimer()
        } else {
            mode = .disconnected
            onModeChange?(.disconnected)
            collapseTimer?.cancel()
            isCollapsed = false
        }
    }

    public func cancel() {
        barInitiatedRecording = false
        releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
        barInitiatedTimeout?.cancel()
        transcriptionTimeoutTask?.cancel()
        recordingIdleCleanupTask?.cancel()
        cancelDeferredFinalTranscription()
        recordStartAckTimeoutTask?.cancel()
        pendingRecordingIdleAfterFinal = false
        pendingIdleAfterAutoPasteCompletion = false
        pendingRecoveredTranscriptionPaste = false
        clearHistoryRetranscriptionRequest(removeSuppression: true)
        clearRecordStartLateRecovery(clearPasteTarget: false)
        keepsPasteFlowEnvelope = false
        transcribingStartedAt = nil
        transcribingStatusText = nil
        frontmostAppOnRecordStart = nil
        recordStartInsertionHandler = nil
        speechDetected = false
        resetAudioLevels()
        hotkeyPhase = .idle
        statusText = ""
        sendIntent(command: .cancel, payload: ["cmd": "cancel"])
        if mode == .recording || mode == .transcribing || mode == .speaking {
            mode = isConnected ? .idle : .disconnected
            onModeChange?(mode)
            if mode == .idle {
                startCollapseTimer()
            } else {
                collapseTimer?.cancel()
                isCollapsed = false
            }
        }
    }

    public func toggle(scope: String = "all", enabled: Bool) {
