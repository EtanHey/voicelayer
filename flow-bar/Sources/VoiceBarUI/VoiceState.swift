    /// Final-text arrival is the selection boundary. No activation/timer hop may
    /// choose a later cursor, and a possibly applied write is never retried.
    private func pasteIntoReadyFocus(_ text: String, operationID: UUID?) {
        let app = frontmostAppProvider()
        let eligibility = focusedTargetEligibilityProvider()
        guard !secureInputEnabledProvider(), eligibility?.isSecure != true else {
            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID,
                refusalNote: "Not pasted: secure input; kept in History")
            return
        }
        let usesTyping = app.map { TerminalPasteTargets.isTerminal($0.bundleIdentifier ?? "")
            || Self.richHostTypingBundleIdentifiers.contains($0.bundleIdentifier ?? "")
            || chromiumFamilyAppDetector($0) } ?? false
        let permitsTypingHost = usesTyping && eligibility.map {
            $0.typingHostRejectionReason(into: app?.processIdentifier ?? -1,
                allowsTerminalGroup: TerminalPasteTargets.isTerminal(app?.bundleIdentifier)) == nil
        } == true
        guard let app, let eligibility,
              permitsTypingHost || eligibility.permitsTyping(into: app.processIdentifier) else {
            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID,
                refusalNote: "Nothing to paste into; kept in History")
            return
        }
        let target = ReadyPasteTarget(app: app, insertion: captureDictationInsertionHandler(),
            matchesFocus: eligibility.matchesCurrentFocus, eligibility: eligibility)
        pasteTranscript(text, for: app, plan: .autoPaste, operationID: operationID, ownedTarget: target)
    }

    /// Refocuses the target app and delivers text through AX or typed key events.
    private func pasteTranscript(
        _ text: String,
        for targetApp: NSRunningApplication?,
        plan: VoicePastePlan,
        allowAXInsertion: Bool = false,
        requiresEditableTarget: Bool = false,
        operationID: UUID? = nil,
        ownedTarget: ReadyPasteTarget? = nil
    ) {
        let recordStartTargetApp = ownedTarget.map { $0.app } ?? (plan == .autoPaste ? targetApp : frontmostAppOnRecordStart)
        let insertionHandler = ownedTarget.map { $0.insertion } ?? (plan == .autoPaste ? recordStartInsertionHandler : nil)
        let legacyReadyInsertion = plan == .autoPaste && ownedTarget == nil
            ? captureDictationInsertionHandler() : nil
        let legacyReadyMatches = plan == .autoPaste && ownedTarget == nil
            ? dictationTargetIdentityProvider() : nil
        let targetBundleID = targetApp?.bundleIdentifier ?? "nil"
        logDiagnostic("paste_begin", details: [
            "plan": String(describing: plan),
            "targetApp": targetBundleID,
            "textLength": String(text.count),
            "hasCapturedInsertion": boolString(insertionHandler != nil),
            "axTrusted": boolString(accessibilityTrustChecker(false)),
        ])

        guard !secureInputEnabledProvider() else {
            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID,
                refusalNote: "Not pasted: secure input; kept in History")
            return
        }
        if let ownedTarget, !ownedTargetIsCurrent(ownedTarget) {
            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
            return
        }
        if let pasteHandler {
            if let targetApp {
                lastPasteTargetApp = targetApp
            }
            if ownedTarget == nil {
                frontmostAppOnRecordStart = nil
                recordStartInsertionHandler = nil
            }
            finishPasteConfirmation(
                outcome: pasteHandler(text) ? .pasted : .failed(Self.genericPasteFailureMessage),
                text: text,
                operationID: operationID
            )
            return
        } else {
            guard let targetApp else {
                if ownedTarget == nil {
                    frontmostAppOnRecordStart = nil
                    recordStartInsertionHandler = nil
                }
                logDiagnostic("paste_no_target", details: [
                    "plan": String(describing: plan),
                    "hasCapturedInsertion": boolString(insertionHandler != nil),
                ])
                finishPasteConfirmation(
                    outcome: plan == .autoPaste ? .notInserted : .failed(Self.genericPasteFailureMessage), text: text,
                    operationID: operationID,
                    refusalNote: "Nothing to paste into; kept in History"
                )
                return
            }

            let pasteDelay = plan == .autoPaste ? pasteConfirmationDelay : plan.pasteDelay
            let schedule: (TimeInterval, @escaping () -> Void) -> Void = ownedTarget == nil
                ? pasteScheduler : { _, work in work() }
            schedule(plan.activationDelay) { [weak self] in
                guard let self else { return }
                let currentFront = frontmostAppProvider()
                let currentIsSelf = currentFront?.bundleIdentifier == Bundle.main.bundleIdentifier
                let currentPasteTarget = !currentIsSelf ? currentFront : nil
                let pasteTarget: NSRunningApplication? = targetApp
                let pasteTargetBundleID = pasteTarget?.bundleIdentifier ?? "nil"
                let targetMatchesRecordStart = Self.sameApp(pasteTarget, recordStartTargetApp)
                let targetMatchesSettingsHistory = Self.sameApp(pasteTarget, settingsHistoryPasteTargetApp)
                let capturedInsertionHandler =
                    plan == .autoPaste && ownedTarget != nil
                        ? insertionHandler
                        : allowAXInsertion && targetMatchesSettingsHistory
                        ? settingsHistoryInsertionHandler
                        : nil

                guard let pasteTarget else {
                    logDiagnostic("paste_no_target", details: [
                        "plan": String(describing: plan),
                        "hasCapturedInsertion": boolString(capturedInsertionHandler != nil),
                    ])
                    finishPasteConfirmation(
                        outcome: .failed(Self.genericPasteFailureMessage), text: text,
                        operationID: operationID
                    )
                    return
                }

                logDiagnostic("paste_before_activate", details: [
                    "plan": String(describing: plan),
                    "targetApp": pasteTargetBundleID,
                    "hasCapturedInsertion": boolString(capturedInsertionHandler != nil),
                    "recordStartPID": recordStartTargetApp.map { String($0.processIdentifier) } ?? "nil",
                    "targetPID": String(pasteTarget.processIdentifier),
                    "targetMatchesRecordStart": boolString(targetMatchesRecordStart),
                    "freshFocusPreferred": boolString(plan == .autoPaste && currentPasteTarget != nil),
                ])
                if let ownedTarget {
                    guard ownedTargetIsCurrent(ownedTarget) else {
                        finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID); return
                    }
                } else { targetAppActivator(pasteTarget) }
                lastPasteTargetApp = pasteTarget
                logDiagnostic("paste_after_activate", details: [
                    "plan": String(describing: plan),
                    "targetApp": pasteTargetBundleID,
                    "hasCapturedInsertion": boolString(capturedInsertionHandler != nil),
                ])

                schedule(pasteDelay) { [weak self] in
                    guard let self else { return }
                    guard !secureInputEnabledProvider() else {
                        finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID,
                            refusalNote: "Not pasted: secure input; kept in History")
                        return
                    }
                    if let ownedTarget, !ownedTargetIsCurrent(ownedTarget) {
                        finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID); return
                    }
                    if plan == .autoPaste, let legacyReadyMatches, !legacyReadyMatches() {
                        finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
                        return
                    }
                    if (plan == .autoPaste || allowAXInsertion),
                       frontmostAppProvider()?.processIdentifier != pasteTarget.processIdentifier {
                        finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
                        return
                    }
                    if plan == .autoPaste, insertionHandler != nil, !targetMatchesRecordStart {
                        logDiagnostic("paste_ax_insert_skipped", details: [
                            "plan": String(describing: plan),
                            "targetApp": pasteTargetBundleID,
                            "reason": "target_mismatch",
                        ])
                    }

                    // Terminals skip AX: AX insertion is unbracketed, so each newline lands
                    // as a Return and submits the line. They get TYPING below —
                    // see the AIDEV-NOTE there and TerminalPasteTargets.
                    let isTerminalTarget = TerminalPasteTargets.isTerminal(pasteTargetBundleID)
                    // Etan's ruling: delivery in these rich hosts uses the
                    // working Shift+F5 typing route, never a whole-document AX write.
                    // PASTE2: Gemini.app (WebKit composer) and every Chromium/Electron/CEF host
                    // join them; AX cannot certify their web composers, so an AX miss there
                    // used to stop at "Not pasted". Native apps try AX before guarded typing.
                    let usesRichHostTyping = Self.richHostTypingBundleIdentifiers.contains(pasteTargetBundleID)
                        || chromiumFamilyAppDetector(pasteTarget)
                    let skipsAX = isTerminalTarget || usesRichHostTyping
                    let requiresFocusedTypingTarget = !skipsAX && (plan == .autoPaste || requiresEditableTarget)
                    let typingEligibility = ownedTarget?.eligibility ?? (requiresFocusedTypingTarget
                        ? focusedTargetEligibilityProvider() : nil)
                    if skipsAX {
                        logDiagnostic("paste_ax_insert_skipped", details: [
                            "plan": String(describing: plan),
                            "targetApp": pasteTargetBundleID,
                            "reason": isTerminalTarget ? "terminal_target" : "rich_host_typed_delivery",
                        ])
                    }
                    let deliveredText = isTerminalTarget
                        ? TerminalPasteTargets.typingText(text, bundleIdentifier: pasteTargetBundleID)
                        : text

                    let freshInsertionHandler =
                        ownedTarget == nil && !skipsAX
                            && (plan == .autoPaste || (allowAXInsertion && capturedInsertionHandler == nil))
                            ? (plan == .autoPaste ? legacyReadyInsertion : captureDictationInsertionHandler())
                            : nil
                    if let freshInsertionHandler {
                        let attempt = beginAXInsertion(
                            freshInsertionHandler,
                            text: text,
                            plan: plan,
                            targetBundleID: pasteTargetBundleID,
                            source: "fresh",
                            operationID: operationID
                        )
                        if attempt == .started {
                            return
                        }
                        if attempt == .busy {
                            rejectCompetingAXInsertion(text: text, plan: plan, operationID: operationID)
                            return
                        }
                    }

                    if !skipsAX, let capturedInsertionHandler {
                        let attempt = beginAXInsertion(
                            capturedInsertionHandler,
                            text: text,
                            plan: plan,
                            targetBundleID: pasteTargetBundleID,
                            source: "captured",
                            operationID: operationID
                        )
                        if attempt == .started {
                            return
                        }
                        if attempt == .busy {
                            rejectCompetingAXInsertion(text: text, plan: plan, operationID: operationID)
                            return
                        }
                    }

                    if isAXInsertionInFlight,
                       activeAXInsertionTargetBundleID == pasteTargetBundleID {
                        rejectCompetingAXInsertion(text: text, plan: plan, operationID: operationID)
                        return
                    }

                    if !usesRichHostTyping {
                        logDiagnostic("paste_ax_insert_miss", details: [
                            "plan": String(describing: plan),
                            "targetApp": pasteTargetBundleID,
                            "hadCapturedInsertion": boolString(capturedInsertionHandler != nil),
                            "attemptedFreshInsertion": boolString(freshInsertionHandler != nil),
                            "axTrusted": boolString(accessibilityTrustChecker(false)),
                        ])
                    }
                    // Only a pre-write AX decline reaches this fallback. Automatic
                    // native delivery also requires the selected ready-time process;
                    // editability alone must not authorize typing into another app.
                    if plan == .autoPaste, !skipsAX {
                        guard recordStartTargetApp?.processIdentifier == pasteTarget.processIdentifier else {
                            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
                            return
                        }
                    }
                    if requiresFocusedTypingTarget {
                        let frontPID = frontmostAppProvider()?.processIdentifier
                        let rejectionReason: String?
                        if frontPID != pasteTarget.processIdentifier {
                            rejectionReason = "frontmost_pid_changed"
                        } else if let typingEligibility {
                            rejectionReason = typingEligibility.typingRejectionReason(into: pasteTarget.processIdentifier)
                        } else {
                            rejectionReason = "eligibility_unavailable"
                        }
                        var details = typingEligibility?.diagnosticDetails ?? [:]
                        details["plan"] = String(describing: plan)
                        details["targetApp"] = pasteTargetBundleID
                        details["targetPID"] = String(pasteTarget.processIdentifier)
                        details["frontmostPID"] = frontPID.map { String($0) } ?? "nil"
                        details["focusedPID"] = typingEligibility.map { String($0.processIdentifier) } ?? "nil"
                        details["role"] = typingEligibility?.role ?? "nil"
                        details["editable"] = typingEligibility.map { String($0.isEditable) } ?? "nil"
                        details["secure"] = typingEligibility.map { String($0.isSecure) } ?? "nil"
                        details["reason"] = rejectionReason ?? "eligible"
                        logDiagnostic("paste_typing_eligibility", details: details)
                        guard rejectionReason == nil else {
                            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
                            return
                        }
                    }
                    // AIDEV-NOTE: Dictation NEVER touches the pasteboard. This is the third
                    // attempt at this line and the first that does not trade one of Etan's
                    // bugs for another, so the whole history lives here, at the call site:
                    //
                    //   1. AX insertion. Unbracketed, so in a terminal every newline lands as
                    //      a Return and submits the line (2026-09-06, TerminalPasteTargets).
                    //   2. Clipboard + Cmd+V, restoring his clipboard after 0.5 s. A race: the
                    //      target reads the pasteboard whenever it gets to it, so it sometimes
                    //      pasted his previous copy, once both concatenated (2026-09-09).
                    //   3. #69 (v2.2.18): clipboard + Cmd+V, leave the transcript on the
                    //      pasteboard. Removed the race by making it permanent: every Cmd+V
                    //      after a dictation pasted the transcript, not what he copied.
                    //      Etan, 2026-09-13: "the transcription is my paste instead of only
                    //      Shift+F5 being paste of last transcript and Command+V being kept
                    //      for only actual clipboard use."
                    //   4. v2.2.19: typed, wrapped in ESC[200~ … ESC[201~. A typed key event
                    //      cannot carry an ESC into cmux: under the kitty keyboard protocol
                    //      Claude Code and Codex turn on, Ghostty types the KEY in place of
                    //      any text holding a control character, and the key was keycode 0,
                    //      `a`. Every dictation arrived as "a…a" and lost the words in its
                    //      first and last event. Etan, 2026-09-13: "keeps doing 'a' at the
                    //      begining and 'a' at the end, or 'aa' for short ones."
                    //
                    // Each earlier fix recorded only the side it fixed. His spec, not
                    // negotiable: Shift+F5 pastes the last transcript; Cmd+V is his clipboard
                    // and only his clipboard; dictation never writes the pasteboard.
                    //
                    // So the transcript is TYPED as printable text only. TerminalPasteTargets
                    // folds line breaks outside cmux; retained breaks use Shift+Return
                    // (SynthesizedTyping). No control character ever rides in
                    // a key event. This route serves terminals, known rich-host automatic
                    // delivery, explicit re-paste and verified editable native targets.
                    // There is no clipboard fallback anywhere, by design: a failed
                    // paste is recoverable with Shift+F5, a paste over his clipboard is not.
                    //
                    // cmux retains its shipped Shift+Return behavior for kitty-protocol
                    // composers. Other terminals fold newlines to spaces so a bare shell
                    // never receives a Return or Shift+Return from a dictated line break.
                    logDiagnostic("paste_path", details: [
                        "plan": String(describing: plan),
                        "targetApp": pasteTargetBundleID,
                        "path": "typing",
                        "terminalTarget": boolString(isTerminalTarget),
                        "trailingNewlineStripped": boolString(isTerminalTarget && TerminalPasteTargets.strippingSingleTrailingNewline(text) != text),
                        "terminalNewlinesFolded": boolString(isTerminalTarget && deliveredText != TerminalPasteTargets.strippingSingleTrailingNewline(text)),
                    ])
                    let typed: Bool
                    if let ownedTarget, let ownedTextTypingHandler {
                        let matches = { [weak self] in self?.ownedTargetIsCurrent(ownedTarget) == true }
                        switch ownedTextTypingHandler(deliveredText, pasteTarget.processIdentifier, matches) {
                        case .posted: typed = true
                        case .failed: typed = false
                        case .focusChanged:
                            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID); return
                        }
                    } else if (plan == .autoPaste || allowAXInsertion), let guardedTextTypingHandler {
                        switch guardedTextTypingHandler(deliveredText, pasteTarget.processIdentifier) {
                        case .posted: typed = true
                        case .failed: typed = false
                        case .focusChanged:
                            finishPasteConfirmation(outcome: .notInserted, text: text, operationID: operationID)
                            return
                        }
                    } else {
                        typed = textTypingHandler(deliveredText)
                    }
                    logDiagnostic("paste_typing_result", details: [
                        "plan": String(describing: plan),
                        "targetApp": pasteTargetBundleID,
                        "typed": boolString(typed),
                        "textLength": String(deliveredText.count),
                    ])
                    finishPasteConfirmation(
                        outcome: Self.pasteOutcome(
                            pasted: typed,
                            plan: plan
                        ),
                        text: deliveredText,
                        operationID: operationID,
                        showsTerminalTranscript: isTerminalTarget
                    )
                }
            }
            if ownedTarget == nil {
                frontmostAppOnRecordStart = nil
                recordStartInsertionHandler = nil
            }
            return
        }
    }

    private func ownedTargetIsCurrent(_ target: ReadyPasteTarget) -> Bool {
        guard let current = frontmostAppProvider(), let captured = target.app,
              current.processIdentifier == captured.processIdentifier,
              Self.sameApp(current, captured) else { return false }
        guard !secureInputEnabledProvider(), target.eligibility?.isSecure != true else { return false }
        if let matchesFocus = target.matchesFocus { return matchesFocus() }
        return false
    }

    private func noteOwnedDelivery(path: String?, text: String, note: String) {
        if let index = recentTranscriptionEntries.firstIndex(where: { path != nil ? $0.recordingPath == path : $0.text == text.trimmingCharacters(in: .whitespacesAndNewlines) }) {
            recentTranscriptionEntries[index].deliveryNote = note
            if lastDictationCardEntry?.recordingPath == recentTranscriptionEntries[index].recordingPath {
                lastDictationCardEntry = recentTranscriptionEntries[index]
            }
        }
    }

    private func captureDictationInsertionHandler() -> AsyncDictationInsertionHandler? {
        if let asyncHandler = asyncDictationInsertionHandlerProvider() {
            return asyncHandler
        }
        guard let synchronousHandler = dictationInsertionHandlerProvider() else {
            return nil
        }
        return { text, completion in
            _ = synchronousHandler(text)
            // A legacy Bool cannot tell rejection from an applied-but-rejected
            // setter. Invocation therefore consumes this attempt without retry.
            completion(.appliedUnverified)
            return true
        }
    }

    private func beginAXInsertion(
        _ handler: AsyncDictationInsertionHandler,
        text: String,
        plan: VoicePastePlan,
        targetBundleID: String,
        source: String,
        operationID: UUID?
    ) -> AXInsertionAttempt {
        guard !isAXInsertionInFlight else {
            return .busy
        }

        isAXInsertionInFlight = true
        activeAXInsertionTargetBundleID = targetBundleID
        var handlerReturned = false
        var completionResult: DictationInsertionResult?
        var didFinish = false
        var reportedOwnedTimeout = false

        let finish = { [weak self] (result: DictationInsertionResult) in
            guard let self, !didFinish else { return }
            didFinish = true
            axInsertionWatchdog?.cancel()
            axInsertionWatchdog = nil
            isAXInsertionInFlight = false
            activeAXInsertionTargetBundleID = nil
            if reportedOwnedTimeout { return }
            logDiagnostic("paste_ax_insert_complete", details: [
                "plan": String(describing: plan),
                "targetApp": targetBundleID,
                "source": source,
                "result": String(describing: result),
            ])
            let outcome: VoicePasteOutcome = switch result {
            case .verified: .insertedAtCursor
            case .notApplied: .notInserted
            case .appliedUnverified: .unverified
            case .partiallyApplied: .partial
            }
            finishPasteConfirmation(outcome: outcome, text: text, operationID: operationID)
        }

        let started = handler(text) { result in
            if handlerReturned {
                finish(result)
            } else {
                completionResult = completionResult ?? result
            }
        }
        handlerReturned = true

        // A completion carries possible application even if a faulty adapter returns
        // false. Suppress fallback in that case too.
        guard started || completionResult != nil else {
            isAXInsertionInFlight = false
            activeAXInsertionTargetBundleID = nil
            return .failed
        }
        logDiagnostic("paste_path", details: [
            "plan": String(describing: plan),
            "targetApp": targetBundleID,
            "path": "ax",
            "source": source,
        ])
        if let completionResult {
            finish(completionResult)
        } else {
            let watchdog = DispatchWorkItem { [weak self] in
                guard let self, !didFinish, isAXInsertionInFlight else { return }
                if let operationID, ownedPasteOperations[operationID] != nil {
                    // Report uncertainty and release daemon FIFO; keep the AX writer mutex until actual completion.
                    axInsertionWatchdog = nil
                    finishPasteConfirmation(outcome: .unverified, text: text, operationID: operationID)
                    reportedOwnedTimeout = true
                    return
                }
                didFinish = true
                axInsertionWatchdog = nil
                isAXInsertionInFlight = false
                activeAXInsertionTargetBundleID = nil
                logDiagnostic("paste_ax_insert_timeout", details: [
                    "plan": String(describing: plan),
                    "targetApp": targetBundleID,
                    "source": source,
                ])
                finishPasteConfirmation(
                    outcome: .unverified,
                    text: text,
                    operationID: operationID
                )
            }
            axInsertionWatchdog = watchdog
            DispatchQueue.main.asyncAfter(
                deadline: .now() + axInsertionCompletionTimeout,
                execute: watchdog
            )
        }
        return .started
    }

    private func rejectCompetingAXInsertion(
        text: String,
        plan: VoicePastePlan,
        operationID: UUID?
    ) {
        logDiagnostic("paste_ax_insert_busy", details: [
            "plan": String(describing: plan),
            "textLength": String(text.count),
        ])
        finishPasteConfirmation(
            outcome: .failed("Text insertion already in progress"),
            text: text,
            operationID: operationID
        )
    }

    private static let genericPasteFailureMessage = "Paste failed. Click the text field and try again."
    private static let pasteFailureRetryMessage = "Paste failed. Click the text field and press Shift+F5."

    private static let richHostTypingBundleIdentifiers: Set<String> = [
        "com.t3tools.t3code", "net.imput.helium", "com.google.GeminiMacOS",
    ]

    private static func pasteOutcome(
        pasted: Bool,
        plan: VoicePastePlan
    ) -> VoicePasteOutcome {
        guard pasted else { return .failed(genericPasteFailureMessage) }
        return .typed
    }

    private static func sameApp(_ lhs: NSRunningApplication?, _ rhs: NSRunningApplication?) -> Bool {
        guard let lhs, let rhs else { return false }
        if let lhsBundleIdentifier = lhs.bundleIdentifier,
           let rhsBundleIdentifier = rhs.bundleIdentifier {
            return lhsBundleIdentifier == rhsBundleIdentifier
        }

        return lhs.processIdentifier == rhs.processIdentifier
    }

    private func finishPasteConfirmation(
        outcome: VoicePasteOutcome,
        text: String,
        operationID: UUID? = nil,
        showsTerminalTranscript: Bool = false,
        refusalNote: String = PasteRecoveryFeedback.notInserted
    ) {
        if let operationID, let delivery = ownedPasteOperations.removeValue(forKey: operationID) {
            completedDictationDeliveries.insert(delivery.deliveryID)
            locallyStartedDictationTakes.remove(delivery.takeID)
            if operationID == latestDictationOperationID {
                latestDictationInsertionStatus = switch outcome {
                case .insertedAtCursor: .insertedAtCursor
                case .pasted: .pasted
                case .notInserted: .notInserted
                case .unverified, .partial: .unverified
                case .typed: .typed
                case .failed: .failed
                }
            }
            if outcome == .notInserted { noteOwnedDelivery(path: delivery.path, text: delivery.text, note: refusalNote) }
            if outcome == .unverified { noteOwnedDelivery(path: delivery.path, text: delivery.text, note: PasteRecoveryFeedback.unverified) }
            var receipt: [String: Any] = ["cmd": "dictation_delivered", "take_id": delivery.takeID, "delivery_id": delivery.deliveryID]
            if outcome == .notInserted { receipt["outcome"] = "not_inserted" }
            if outcome == .unverified { receipt["outcome"] = "unverified" }
            sendCommand?(receipt)
            if microphoneTakeID == nil {
                let message: String = switch outcome {
                case .insertedAtCursor, .pasted: text
                case .typed: PasteDeliveryFeedback.typed
                case .notInserted: refusalNote
                case .unverified: PasteRecoveryFeedback.unverified
                case .partial: PasteRecoveryFeedback.partial
                case let .failed(message): Self.failureMessageWithRetryHint(message)
                }
                showConfirmation(message, duration: 5.0)
            }
            return
        }
        if let operationID, operationID == latestDictationOperationID {
            latestDictationInsertionStatus = switch outcome {
            case .insertedAtCursor: .insertedAtCursor
            case .pasted: .pasted
            case .notInserted: .notInserted
            case .unverified, .partial: .unverified
            case .typed: .typed
            case .failed: .failed
            }
        }
        logDiagnostic("paste_confirmation", details: [
            "outcome": String(describing: outcome),
        ])
        switch outcome {
        case .insertedAtCursor:
            showConfirmation(text, duration: 5.0)
        case .pasted:
            showConfirmation(text, duration: 5.0)
        case .notInserted:
            showConfirmation(refusalNote, duration: 5.0)
        case .unverified:
            // Terminal confirmation keeps the dictated words; the receipt above
            // still reports posted events as unverified, without claiming readback.
            showConfirmation(
                showsTerminalTranscript ? text : PasteRecoveryFeedback.unverified,
                duration: 5.0
            )
        case .typed:
            // Terminal confirmation keeps the dictated words. Posted key events are not
            // readback, so the pill says only what happened: "Typed".
            showConfirmation(
                showsTerminalTranscript ? text : PasteDeliveryFeedback.typed,
                duration: 5.0
            )
        case .partial:
            showConfirmation(PasteRecoveryFeedback.partial, duration: 5.0)
        case let .failed(message):
            showConfirmation(Self.failureMessageWithRetryHint(message), duration: 4.0)
        }

        // A failed or recovery outcome keeps its own message; it already points at History, which has the note.
        if let notice = pendingMicDisconnectNotice, let operationID, operationID == latestDictationOperationID {
            pendingMicDisconnectNotice = nil
            switch outcome {
            case .insertedAtCursor, .pasted, .unverified, .typed:
                showConfirmation(notice, duration: Self.micDisconnectNoticeSeconds)
            case .notInserted, .partial, .failed:
                break
            }
        }

        if pendingIdleAfterAutoPasteCompletion {
            pendingIdleAfterAutoPasteCompletion = false
            pendingRecoveredTranscriptionPaste = false
            historyRetranscriptionRequest.clear(removeSuppression: false)
            enterIdleState(clearQueue: false)
        }
    }

    static let micDisconnectNoticeSeconds: TimeInterval = 6.0
    /// MICDROP2 notice waiting for the current dictation's paste confirmation; cleared by the next recording.
    var pendingMicDisconnectNotice: String?

    private func showConfirmation(_ message: String, duration: TimeInterval = 1.5) {
        confirmationText = message
        DispatchQueue.main.asyncAfter(deadline: .now() + duration) { [weak self] in
            if self?.confirmationText == message {
                self?.confirmationText = nil
                self?.keepsPasteFlowEnvelope = false
            }
        }
    }

    private static func failureMessageWithRetryHint(_ message: String) -> String {
        if message == genericPasteFailureMessage {
            return pasteFailureRetryMessage
        }
        return message
    }

    private func sendIntent(
        command: IntentCommand,
        payload: [String: Any],
        trackPending: Bool = true,
        retiresSelections: Bool = true
    ) {
        // Speech-only retirement; recorder intent payloads and stop/cancel bodies stay unchanged.
        if retiresSelections, command == .stop || command == .cancel { invalidateSelectionSpeechIdentity() }
        if command == .stop || command == .cancel { supersedePendingSpeechSeek() }
        let id = UUID().uuidString
        var payloadWithID = payload
        payloadWithID["id"] = id
        if trackPending {
            // An early PTT release must not mask a failed record start.
            if command == .stop, pendingIntent?.command == .record {
                sendCommand?(payloadWithID)
                return
            }
            recordStartAckTimeoutTask?.cancel()
            pendingIntent = PendingIntent(id: id, command: command)
            if command == .record {
                scheduleRecordStartAckTimeout(id: id)
            }
        }
        sendCommand?(payloadWithID)
    }

    public func handleCommandDeliveryFailure(
        _ command: [String: Any],
        reason: String = "VoiceLayer is starting"
    ) {
        guard let commandName = command["cmd"] as? String,
              let id = command["id"] as? String,
              !id.isEmpty
        else {
            return
        }

        if commandName == "speak_text" {
            handleEvent([
                "type": "ack", "command": commandName, "outcome": "reject",
                "id": id, "reason": reason,
            ])
            return
        }
        guard let intentCommand = IntentCommand(rawValue: commandName) else { return }

        handleEvent([
            "type": "ack",
            "command": intentCommand.rawValue,
            "outcome": "reject",
            "id": id,
            "reason": reason,
        ])
    }

    private func scheduleRecordStartAckTimeout(id: String) {
        let timeout = recordStartAckTimeout
        recordStartAckTimeoutTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: timeout)
            guard let self,
                  !Task.isCancelled,
                  pendingIntent?.id == id,
                  pendingIntent?.command == .record
            else {
                return
            }

            handleEvent([
                "type": "ack",
                "command": IntentCommand.record.rawValue,
                "outcome": IntentOutcome.reject.rawValue,
                "id": id,
                "reason": "VoiceLayer is starting",
            ])
        }
    }

    private func scheduleRecordStartLateRecovery() {
        canRecoverLateRecordStart = true
        recordStartLateRecoveryTask?.cancel()
        let window = recordStartLateRecoveryWindow
        recordStartLateRecoveryTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: window)
            guard let self, !Task.isCancelled, canRecoverLateRecordStart else { return }
            clearRecordStartLateRecovery(clearPasteTarget: true)
        }
    }

    private func clearRecordStartLateRecovery(clearPasteTarget: Bool) {
        canRecoverLateRecordStart = false
        recordStartLateRecoveryTask?.cancel()
        recordStartLateRecoveryTask = nil
        if clearPasteTarget {
            if case .opening = deferredBarRecording { deferredBarRecording = nil }
            frontmostAppOnRecordStart = nil
            recordStartInsertionHandler = nil
        }
    }

