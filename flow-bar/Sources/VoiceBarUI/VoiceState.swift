    public func handleEvent(
        _ event: [String: Any],
        playbackAmplitude: PlaybackAmplitudeEnvelope? = nil
    ) {
        guard let type = event["type"] as? String else { return }
        // A stopped legacy capture no longer delays Quit after settlement, failure,
        // or replacement. Failure/disconnect is not archive proof; the raw WAV remains.
        if type == "error" || (type == "state" &&
            (["idle", "recording"].contains(event["state"] as? String ?? "") ||
             (event["state"] as? String == "transcribing" && event["stt_audio_ms"] != nil))) {
            quitAwaitingLegacyArchive = false
        }
        defer { finishDeferredRecordingOpen(event) }
        if !historyRunLog.runs.isEmpty, ["ack", "transcription", "error", "state"].contains(type) {
            historyRunLog.observe(event)
        }

        if handleOwnedRecordingEvent(event, type: type) { return }

        switch type {
        case "clone_engine":
            if let snapshot = CloneEngineSnapshot(payload: event) { cloneEngine = snapshot }
        case "history_playback_gate":
            if let id = event["id"] as? String, let busy = event["busy"] as? Bool {
                MainActor.assumeIsolated { historyPlayback.setVoiceOwner(
                    id,
                    busy: busy,
                    pid: (event["owner_pid"] as? Int32) ?? 0
                ) }
            }

        case "state":
            guard let stateStr = event["state"] as? String else { return }
            if event["preserves_paused_read"] as? Bool == true, askParkedRead == nil { askParkedRead = parkedRead }
            switch stateStr {
            case "idle":
                if event["restores_paused_read"] as? Bool == true {
                    guard let parked = askParkedRead,
                          event["playback_id"] as? String == parked.playbackID,
                          (event["generation"] as? NSNumber)?.intValue == parked.generation else { return }
                    askParkedRead = nil
                    guard (mode == .idle || mode == .speaking), deferredBarRecording == nil else {
                        parkedRead = parked
                        return // Another capture owns the surface; its recording-idle restores this park.
                    }
                    enterIdleState(clearQueue: false)
                    parkedRead = parked
                    isCaptureSettlementPending = false
                    restoreParkedReadIfSettled()
                    return
                }
                if !supportsRecordingJobs, queuedRecordingTakeID != nil,
                   event["source"] as? String == "recording" {
                    microphoneTakeID = nil
                    isRecordingDrainPending = false
                    stoppingBarTakeID = nil
                    startQueuedRecordingIfCaptureReleased()
                    return
                }
                let idleSource = event["source"] as? String
                // The daemon never sends a playback idle while a read is parked: one now means it is gone.
                // (While speaking, the speaking → idle edge retires it once the readback froze its position.)
                if idleSource == "playback", mode != .speaking { retireParkedRead() }
                // The daemon's recording-idle is capture settlement (TLA+ AuthoritativeCaptureSettleRestore). It
                // never ends a paused read: that is playback's Stop, outcome or replacement, not capture's idle.
                if idleSource == "recording" {
                    isCaptureSettlementPending = false
                    if mode == .speaking {
                        modelsRecordingBusy = false
                        modelsRecordingReason = nil
                        releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
                        return
                    }
                    if parkedRead != nil { scheduleParkedReadRestore() }
                }
                if barInitiatedRecording, mode == .transcribing {
                    // Ignore passive-client idle until the owning recording settles.
                    if idleSource != "recording" {
                        return
                    }
                }
                // AIDEV-NOTE: Do not reset barInitiatedRecording on generic idle.
                // Non-recording idle can still arrive from passive clients or
                // playback while the command-owning daemon is transcribing. These
                // stale idle events would kill the paste flag. Recording-sourced
                // idle gets a short final-transcript grace before clearing it.
                if idleSource == "recording" {
                    modelsRecordingBusy = false
                    modelsRecordingReason = nil
                    releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
                    barInitiatedTimeout?.cancel()
                    if historyRetranscriptionRequest.currentPath() != nil {
                        historyRetranscriptionRequest.clear(removeSuppression: true)
                    }
                    scheduleRecordingIdleCleanupIfNeeded()
                }
                if idleSource == "recording", mode == .error, errorMessage != nil {
                    return
                }
                if idleSource == "playback", event["next_state"] as? String == "recording" {
                    enterPlaybackToRecordingTransition()
                } else {
                    enterIdleState(clearQueue: idleSource == "playback")
                }
                if idleSource == "recording" { refreshModelsBusy() }
            case "speaking":
                let previousHold = event["previous_read_hold"] as? [String: Any]
                let heldID = previousHold?["playback_id"] as? String
                let heldGeneration = previousHold?["generation"] as? Int
                let lendsPresentation = mode == .speaking && heldID != nil
                    && ((currentPlayback != nil && heldID == currentPlayback?.id)
                        || (currentUtteranceID != nil && previousHold?["utterance_id"] as? String == currentUtteranceID))
                    && heldGeneration.map { $0 > 0 && $0 >= (currentPlayback?.generation ?? 0) } == true
                let previousReturn = event["previous_read_return"] as? [String: Any]
                if let previousReturn {
                    // The saved loan survives Stop/legacy idle, but never a superseding presentation.
                    guard let held = previousReadPresentation, mode == .speaking || mode == .idle,
                          mode == .idle || currentPlayback?.id == held.borrower,
                          previousReturn["from_playback_id"] as? String == held.borrower,
                          previousReturn["pause_owner"] as? String == "user",
                          let offset = previousReturn["offset_ms"] as? Int, offset >= 0,
                          event["playback_id"] as? String == held.id,
                          event["request_id"] as? String == held.request,
                          let generation = event["generation"] as? Int, generation >= held.generation else {
                        logSpeakingDrop(event, reason: "wrong-return-owner")
                        return
                    }
                    // Optimistic Stop can retire this unended loan; only its exact return reactivates it.
                    if let request = held.request { selectionRetiredRequestIDs.removeAll { $0 == request } }
                }
                let requestID = event["request_id"] as? String
                if let requestID, selectionRetiredRequestIDs.contains(requestID) {
                    logSpeakingDrop(event, reason: "retired-request")
                    return
                }
                if let requestID { selectionUnacknowledgedRequestIDs.remove(requestID) }
                let submission = requestID.flatMap { selectionSubmissions[$0] }
                // An external read changes the current read, but cannot supersede pending own
                // submissions. Only an acknowledged newer own request establishes their order.
                // Receipts may arrive out of order; never roll a newer read back to an older one.
                if let submission, submission.order < selectionReceiptOrder {
                    logSpeakingDrop(event, reason: "older-receipt")
                    return
                }
                if lendsPresentation, let heldID, let heldGeneration, let borrower = event["playback_id"] as? String {
                    previousReadPresentation = (heldID, heldGeneration, borrower, selectionReadRequestID, currentReadSnapshot())
                } else if previousReturn == nil, let held = previousReadPresentation,
                          event["playback_id"] as? String != held.borrower, event["preserves_paused_read"] as? Bool != true {
                    previousReadPresentation = nil
                }
                if event["preserves_paused_read"] as? Bool != true { askParkedRead = nil }
                if let submission {
                    selectionQueueSnapshotIsEmpty = false
                    selectionReceiptOrder = submission.order
                    let superseded = selectionSubmissions.filter { $0.value.order < submission.order }.map(\.key)
                    for id in superseded { retireSelectionRequest(id) }
                }
                let isPreparing = (event["long_read"] as? [String: Any])?["preparing"] as? Bool == true
                let readID = (event["long_read"] as? [String: Any])?["id"] as? String
                let acknowledgesSubmission: Bool
                if requestID != nil {
                    acknowledgesSubmission = submission != nil
                } else {
                    // Legacy peers have no identity; preserve their existing heuristic.
                    acknowledgesSubmission = selectionSubmittedText.map { submitted in
                        isPreparing || (event["text"] as? String).map {
                            Self.normalizedSelection($0) == Self.normalizedSelection(submitted)
                        } == true
                    } ?? false
                }
                if readID == nil || readID != selectionReadID || (requestID != nil && requestID != selectionReadRequestID) {
                    if requestID != selectionReadRequestID {
                        clearCurrentSelectionReadIdentity(advanceEpoch: false, retireCurrent: !lendsPresentation)
                    }
                    // A different read supersedes this capture, without becoming a user Stop.
                    if !acknowledgesSubmission, selectionCaptureInFlight { selectionCaptureCancelled = true }
                    selectionReadID = readID
                    selectionReadText = submission?.text ?? (acknowledgesSubmission ? selectionSubmittedText : nil)
                    selectionReadRequestID = requestID ?? (acknowledgesSubmission ? selectionSpeechRequestID : nil)
                    if acknowledgesSubmission, requestID == nil || requestID == selectionSpeechRequestID {
                        selectionSubmittedText = nil
                    } else if requestID != nil, !acknowledgesSubmission {
                        selectionSubmittedText = nil
                        selectionSpeechRequestID = nil
                    }
                }
                selectionReadIsPreparing = isPreparing
                selectionReadHash = event["text_hash"] as? String
                pendingIdleAfterAutoPasteCompletion = false
                pendingRecoveredTranscriptionPaste = false
                clearHistoryRetranscriptionRequest(removeSuppression: false)
                clearRecordStartLateRecovery(clearPasteTarget: true)
                transcribingStartedAt = nil
                // WORDTIME1: chunk identity is read + chunk start; text equality is not identity.
                let previousChunk = mode == .speaking ? (read: playbackLongReadID, start: playbackChunkStartMilliseconds) : nil
                let previousLongRead = mode == .speaking ? playbackLongReadID.map {
                    (id: $0, duration: playbackDurationMilliseconds, growing: isPlaybackDurationGrowing)
                } : nil
                let shownPosition = mode == .speaking && !isPlaybackPaused ? playbackElapsedMilliseconds() : 0
                // #809 P1: a new logical read (after idle, or another utterance) retires every pending click's read.
                let edgeUtteranceID = event["utteranceId"] as? String
                // Lane B (QA 11:47 k03-21/k07-29/k04-63): an edge of the read already playing that would move the clock
                // backwards without a re-anchor (seek, resume, replay, resync) is stale: the clock it shows is kept.
                let continuesRead = mode == .speaking && !isPlaybackPaused && edgeUtteranceID != nil
                    && edgeUtteranceID == currentUtteranceID && playbackStartedAt != nil && !isPlaybackPreparing
                // Only a daemon that reports its player's position also marks its re-anchors; an older one's seek
                // edges carry no `reanchor`, so the guard never refuses them.
                // C4 F7: an edge at another speed is never stale: keeping the old clock would run the highlight at the
                // old rate over audio at the new one, landing clicks and the highlight on neighbouring words.
                let keepsClock = continuesRead && daemonReportsPosition && event["reanchor"] == nil
                    && Self.playbackRate(event["playback_rate"]) == playbackRate
                    && ((event["playback_offset_ms"] as? NSNumber)?.intValue).map { $0 < shownPosition - 300 } == true
                if keepsClock { logDiagnostic("stale_speaking_edge_clock_kept", details: ["shown_ms": String(shownPosition)]) }
                let keptClock = keepsClock ? (startedAt: playbackStartedAt, start: playbackChunkStartMilliseconds,
                                              end: playbackChunkEndMilliseconds, rate: playbackRate) : nil
                if let id = event["playback_id"] as? String, id == resyncRequestedFor { resyncRequestedFor = nil }
                if mode != .speaking || edgeUtteranceID != currentUtteranceID ||
                    (edgeUtteranceID == nil && (event["playback_id"] as? String) != currentPlayback?.id) {
                    logicalReadEpoch += 1
                    // Sol R902 P3: a waiting click belongs to the read it was made on; the new read never shows it.
                    supersedePendingSpeechSeek()
                }
                currentUtteranceID = edgeUtteranceID
                resetAudioLevels()
                let playbackStart = playbackAmplitudeClock()
                let offset = (event["playback_offset_ms"] as? NSNumber)?.doubleValue
                let validOffset = offset.flatMap { $0.isFinite && $0 >= 0 ? $0 : nil }
                playbackRate = Self.playbackRate(event["playback_rate"])
                narrationOrigin = Self.narrationOriginName(event["narration_source"] as? String)
                playbackStartedAt = playbackStart - (validOffset ?? 0) / 1000 / playbackRate
                isPlaybackPreparing = isPreparing
                playbackReadbackID = event["readback_id"] as? String
                playbackReadbackDurationMilliseconds = (event["readback_duration_ms"] as? NSNumber)?.intValue
                playbackChunkStartMilliseconds = (event["long_read"] as? [String: Any])?["chunk_start_ms"] as? Int ?? 0
                let longRead = event["long_read"] as? [String: Any]
                let longReadID = longRead?["id"] as? String
                let duration = (event["duration_ms"] as? NSNumber)?.intValue
                let growing = longRead != nil && longRead?["estimated_total_ms"] == nil
                // A chunk edge of the same read never undoes a total its playback_duration already reported.
                if let previousLongRead, longReadID == previousLongRead.id, let previous = previousLongRead.duration {
                    playbackDurationMilliseconds = max(previous, duration ?? 0)
                    isPlaybackDurationGrowing = previousLongRead.growing && growing
                } else {
                    playbackDurationMilliseconds = duration
                    isPlaybackDurationGrowing = growing
                }
                playbackLongReadID = longReadID
                if longReadID == nil || longReadID != playbackTimelineReadID { playbackTimelineChunks = [:] }
                playbackTimelineReadID = longReadID
                // TELE1: the next chunk of the document on screen continues the page from its first word.
                // Only a seek, a new read or anything off the document restarts the teleprompter.
                let advancesDocument = isShowingLongReadDocument && longReadID != nil && previousChunk?.read == longReadID &&
                    (longRead?["chunk_index"] as? Int).map { $0 == (longReadDocumentChunkIndex ?? -2) + 1 } == true &&
                    validOffset.map { Int($0.rounded()) == playbackChunkStartMilliseconds } == true
                if !advancesDocument { playbackEpoch += 1 }
                playbackClockFloorMilliseconds = advancesDocument ? shownPosition : 0
                let chunkDuration = (event["chunk_duration_ms"] as? NSNumber)?.intValue
                playbackChunkEndMilliseconds = chunkDuration.flatMap { $0 > 0 ? playbackChunkStartMilliseconds + $0 : nil }
                if let keptClock {
                    playbackStartedAt = keptClock.startedAt
                    playbackChunkStartMilliseconds = keptClock.start
                    playbackChunkEndMilliseconds = keptClock.end
                    playbackRate = keptClock.rate
                    playbackClockFloorMilliseconds = shownPosition
                }
                playbackAmplitudeEnvelope = playbackAmplitude
                playbackAmplitudeStartedAt = playbackAmplitude.map { _ in playbackStart }
                // X1-34 (C6 L3): Hide is independent of Pause, so resuming the same parked player keeps a teleprompter
                // the eye hid ("reading playing hidden"). Any other read starts shown. Read before the clears below.
                let keepsHiddenOnResume = isTeleprompterDismissed && parkedRead?.playbackID != nil &&
                    parkedRead?.playbackID == event["playback_id"] as? String
                clearRetainedTeleprompter()
                // A speaking event precedes the fresh subtitle payload. Do not let
                // timings from the previous utterance animate a similar new one.
                let sameChunk = validOffset != nil && statusText == event["text"] as? String &&
                    previousChunk?.read == longReadID && previousChunk?.start == playbackChunkStartMilliseconds
                if !sameChunk {
                    // Entering a chunk of this read (a seek back) restores the timings it already had.
                    let stored = playbackTimelineChunks[playbackChunkStartMilliseconds]
                    wordBoundaries = stored?.text == event["text"] as? String ? stored?.words ?? [] : []
                }
                if previousReturn != nil, let held = previousReadPresentation,
                   held.id == event["playback_id"] as? String {
                    restoreLongReadDocument(held.read.document)
                    speechWords = held.read.speechWords
                    previousReadPresentation = nil
                }
                updateLongReadDocument(longRead, readbackID: playbackReadbackID,
                                       chunkText: event["text"] as? String ?? "", displayValue: event["display"])
                mode = .speaking
                isTeleprompterDismissed = keepsHiddenOnResume
                // Every speaking edge is the daemon playing: the resumed read or its replacement.
                retireParkedRead()
                currentPlayback = (event["playback_id"] as? String).flatMap { id in
                    (event["generation"] as? NSNumber).map { (id, $0.intValue) }
                }
                statusText = event["text"] as? String ?? ""
                // U5: a new utterance replaces the word table; its chunks and seeks keep it.
                let utteranceID = event["utteranceId"] as? String
                if speechWords?.utteranceID != utteranceID { speechWords = utteranceID.map(SpeechWordTable.init) }
                // Consume startup timing before announcing speaking to observers.
                if var timing = event["initial_timing"] as? [String: Any], timing["type"] as? String == "subtitle" {
                    if let number = timing["estimated_duration_ms"] as? NSNumber, number.doubleValue.isFinite,
                       let duration = Int(exactly: number.doubleValue.rounded()), duration > 0 {
                        let tokens = TeleprompterContentModel.displayTokens(statusText)
                        let span = max(duration, tokens.count)
                        timing["aligned_words"] = tokens.enumerated().map { index, text -> [String: Any] in
                            let start = Int(Double(index) / Double(tokens.count) * Double(span))
                            let end = Int(Double(index + 1) / Double(tokens.count) * Double(span))
                            return ["word_index": index, "text": text, "offset_ms": start,
                                    "duration_ms": end - start, "estimated": true]
                        }
                        timing["duration_ms"] = span
                    }
                    handleEvent(timing)
                }
                canReplay = true
                hotkeyPhase = .idle
                if let previousReturn {
                    var pause = event
                    pause["state"] = "paused"
                    pause["offset_ms"] = previousReturn["offset_ms"]
                    pause["pause_owner"] = previousReturn["pause_owner"]
                    handlePlaybackStateEvent(pause)
                }
                onModeChange?(.speaking)
                expandFromCollapse()
            case "recording":
                if let captureID = (event["capture_id"] as? NSNumber)?.intValue {
                    inputDeviceLossMonitor?.beginCapture(captureID: captureID)
                    recordingCaptureID = captureID
                }
                isRecordingHandoffPending = false
                pendingMicDisconnectNotice = nil
                let startsNewRecording = mode != .recording
                // AIDEV-NOTE: `bar_owned` is optional on the wire. Only explicit `true` confirms
                // a local bar capture; explicit `false` confirms remote ownership, while absence
                // leaves the ownership gate untouched and fails closed for auto-paste.
                // Absent is not evidence of local ownership. It is absence of evidence.
                let barOwned = event["bar_owned"] as? Bool
                let captureIsRemoteOwned = barOwned != true
                // A remote MCP capture emits a `recording` event that is otherwise
                // indistinguishable from a dropped-ack F5 press, so without this the late-recovery
                // branch below claims it and the remote caller's answer gets auto-pasted into the
                // frontmost app. The 10s recovery window makes that a RACE — a remote capture
                // starting inside the window is hijacked, outside it is fine.
                // Live repro 2026-07-26 12:55:30.
                if barOwned == false {
                    remoteOwnedRecording = true
                    supersededRemoteTranscriptPending = false
                }
                if captureIsRemoteOwned {
                    // A remote capture supersedes any bar claim on the line.
                    barInitiatedRecording = false
                    barInitiatedTimeout?.cancel()
                } else {
                    // An authoritative local-owner event resolves any earlier request race.
                    releaseRemoteCaptureOwnership(preservingPossibleTranscript: false)
                }
                if pendingIntent?.command == .record {
                    recordStartAckTimeoutTask?.cancel()
                    pendingIntent = nil
                } else if canRecoverLateRecordStart, !captureIsRemoteOwned {
                    barInitiatedRecording = true
                }
                clearRecordStartLateRecovery(clearPasteTarget: false)
                pendingIdleAfterAutoPasteCompletion = false
                pendingRecoveredTranscriptionPaste = false
                if !supportsRecordingJobs { clearHistoryRetranscriptionRequest(removeSuppression: false) }
                transcribingStartedAt = nil
                transcribingStatusText = nil
                errorMessage = nil
                resetPlaybackAmplitude()
                if recordingStateUptimeMs == nil {
                    recordingStateUptimeMs = currentRecordingUptimeMs()
                    lastCaptureDurationMs = nil
                    daemonSttAudioMs = nil
                    didLogFirstRecordingAudioLevel = false
                    captureLive = false
                }
                clearRetainedTeleprompter()
                if startsNewRecording {
                    recordingWaveformHistory = WaveformEnvelopeHistory()
                    transcribingWaveformReplayStartedAt = nil
                    localRecordingLevel = nil
                }
                mode = .recording
                recordingMode = event["mode"] as? String
                silenceMode = event["silence_mode"] as? String
                if startsNewRecording {
                    speechDetected = false
                }
                refreshAudioLevel()
                if startsNewRecording {
                    appendRecordingWaveformSample()
                }
                canReplay = false // User recording — replay not applicable
                onModeChange?(.recording)
                expandFromCollapse()
            case "transcribing":
                if let sttAudioMs = (event["stt_audio_ms"] as? NSNumber)?.intValue, sttAudioMs > 0 {
                    daemonSttAudioMs = sttAudioMs
                }
                if deferredRecordingTakeID == nil && !showsReadingProcessingSpinner { enterTranscribingMode() }
            default:
                break
            }

        case "recognizer_status":
            handleRecognizerEvent(event)

        case "ack":
            if ["set_recognizer", "set_recognizer_residency", "download_recognizer", "delete_recognizer", "cancel_recognizer_download",
                RecognizerUnloadWhenIdle.command].contains(event["command"] as? String ?? "") { handleRecognizerEvent(event) }
            handleAckEvent(event)

        case "read_processing":
            guard let id = event["utterance_id"] as? String else { return }
            if event["active"] as? Bool == true { processingReadID = id }
            else if processingReadID == id { processingReadID = nil }

        case "read_queue":
            readQueueCount = max(0, (event["count"] as? NSNumber)?.intValue ?? 0)
            readQueueCurrentRequestID = event["current_request_id"] as? String
            selectionQueueSnapshotIsEmpty = readQueueCount == 0 && readQueueCurrentRequestID == nil
            if selectionQueueSnapshotIsEmpty {
                clearCurrentSelectionReadIdentity()
                let retired = selectionSubmissions.keys.filter { !selectionUnacknowledgedRequestIDs.contains($0) }
                for id in retired { retireSelectionRequest(id) }
                if let id = selectionSpeechRequestID, !selectionUnacknowledgedRequestIDs.contains(id) {
                    selectionSpeechRequestID = nil
                    selectionSubmittedText = nil
                }
            }

        case "playback_state":
            handlePlaybackStateEvent(event)

        case "playback_outcome":
            if let id = event["playback_id"] as? String, let parked = askParkedRead,
               id == parked.playbackID || id == parked.read.longReadID { askParkedRead = nil }
            // Stop or replacement settled the parked job: there is nothing left to resume.
            if let id = event["playback_id"] as? String, let parked = parkedRead,
               id == parked.playbackID || id == parked.read.longReadID {
                if event["reason"] as? String == "resume-refused" {
                    let read = parked.read
                    let document = read.document.isShowing ? read.document.document : nil
                    retainedReadbackID = read.readbackID
                    retainedPlaybackDurationMilliseconds = read.readbackDurationMs ?? read.durationMs
                    retainedPlaybackPositionMilliseconds = parked.offsetMs
                    retainedTeleprompterText = document?.text ?? read.text
                    retainedTeleprompterWordBoundaries = document?.boundaries ?? read.words
                    retainedDisplayBlocks = document?.displayBlocks ?? read.document.display?.blocks ?? []
                    if mode == .speaking { enterIdleState(clearQueue: false) }
                    showSelectionBusyNote(message: "Speech stopped")
                }
                // A terminal paused player cannot become a running highlight clock while its
                // replacement is still synthesizing. Freeze its readback before removing the park.
                if mode == .speaking { enterIdleState(clearQueue: true) }
                clearCurrentSelectionReadIdentity()
                retireParkedRead()
            }

        case "transcription_status":
            guard mode == .transcribing else { return }
            let message = (event["message"] as? String)?
                .trimmingCharacters(in: .whitespacesAndNewlines)
            transcribingStatusText = message?.isEmpty == false ? message : nil

        case "polish_degraded":
            guard let reason = event["reason"] as? String,
                  let hint = event["hint"] as? String
            else { return }
            let degradation = STTPolishDegradation(reason: reason, hint: hint)
            guard degradation != polishDegradation,
                  degradation != dismissedPolishDegradation
            else { return }
            polishDegradation = degradation
            polishMenuSignalPending = true
            onPolishStatusChange?()

        case "polish_ready":
            guard polishDegradation != nil || dismissedPolishDegradation != nil || polishMenuSignalPending
            else { return }
            polishDegradation = nil
            dismissedPolishDegradation = nil
            polishMenuSignalPending = false
            onPolishStatusChange?()

        case "speech":
            if let detected = event["detected"] as? Bool {
                // The accepted gold damping is a pre-speech treatment. Once
                // speech begins, keep the recording on the full-gain path
                // until the recording state itself resolves.
                speechDetected = mode == .recording
                    ? speechDetected || detected
                    : detected
            }

        case "transcription":
            // The remote Ask owns this result; the returned read keeps its clock and presentation.
            if showsReadingProcessingSpinner {
                if event["partial"] as? Bool != true {
                    let text = (event["text"] as? String ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                    let path = event["recording_path"] as? String
                    if !text.isEmpty {
                        rememberRecentTranscription(text, recordingPath: path)
                        refreshTranscriptionVocabulary()
                    }
                    if let path, !path.isEmpty { onHistoryArchiveChange?(path) }
                    releaseRemoteCaptureOwnership(preservingPossibleTranscript: false)
                }
                return
            }
            if let text = event["text"] as? String {
                let isPartial = (event["partial"] as? Bool) == true
                let recordingPath = (event["recording_path"] as? String)?
                    .trimmingCharacters(in: .whitespacesAndNewlines)
                let normalizedRecordingPath = recordingPath?.isEmpty == false ? recordingPath : nil
                let recordingCreatedAt = (event["recording_created_at"] as? String)
                    .flatMap(SettingsArchiveScanner.parseISODate)
                let recordingIsLatest = (event["recording_is_latest"] as? Bool) == true
                let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)

                // AIDEV-NOTE: a late History result belongs to no live capture. Classify it before ANY live state:
                // the polish metadata, the partial `transcript`, the empty-final failTranscription(), and the
                // display-floor deferral, which holds one final at a time. Any of those let a late archived result
                // overwrite or cancel the current dictation's final, and its words were lost (#186 review round 3,
                // #188 review round 1: an empty late result failed the new dictation).
                if let path = normalizedRecordingPath, historyRetranscriptionRequest.isLateArchivedResult(for: path) {
                    handleLateArchivedTranscription(
                        trimmed,
                        recordingPath: path,
                        isPartial: isPartial,
                        recordingCreatedAt: recordingCreatedAt,
                        recordingIsLatest: recordingIsLatest
                    )
                    return
                }

                if !isPartial {
                    lastTranscriptionPolished = event["polished"] as? Bool
                    lastTranscriptionPolishReason = event["polish_reason"] as? String
                }
                guard !trimmed.isEmpty else {
                    if isPartial {
                        return
                    }
                    failTranscription()
                    return
                }

                if isPartial {
                    transcript = trimmed
                    return
                }

                let isHistoryRetranscription = normalizedRecordingPath.map {
                    historyRetranscriptionRequest.suppressesPaste(for: $0)
                } ?? false
                let dictationReceipt = normalizedRecordingPath != nil && !isHistoryRetranscription
                    ? DictationReceipt.parse(event["dictation_receipt"])
                    : nil

                // N8: history retention and paste dispatch belong to the final-result event.
                // Presentation timing must never hold or supersede the words.
                handleFinalTranscription(
                    trimmed,
                    recordingPath: normalizedRecordingPath,
                    dictationReceipt: dictationReceipt,
                    recordingCreatedAt: recordingCreatedAt,
                    recordingIsLatest: recordingIsLatest
                )
            }

        case "playback_position":
            handlePlaybackPosition(event)
        case "playback_session":
            // Lane B: the daemon's one PlaybackSession (formal/playback-session). Additive; the speaking and
            // playback_state edges stay authoritative for what is on screen.
            if let speed = (event["speed"] as? NSNumber)?.doubleValue, Self.playbackSpeeds.contains(speed) { playbackSpeed = speed }
            previousReadAvailable = event["previous_available"] as? Bool ?? false
        case "playback_duration":
            // SCRUB1: a long read's total grows as chunks synthesize; `final` drops "so far".
            // Preparation has no duration yet; the first speaking edge carries its own.
            guard mode == .speaking, let current = playbackDurationMilliseconds, let id = event["long_read_id"] as? String,
                  id == playbackLongReadID, let duration = (event["duration_ms"] as? NSNumber)?.intValue, duration > 0 else { return }
            playbackDurationMilliseconds = max(current, duration)
            if event["final"] as? Bool == true { isPlaybackDurationGrowing = false }

        case "speech_words":
            if var table = speechWords, table.apply(event) { speechWords = table }
            firePendingSpeechSeekIfTimed()

        case "subtitle":
            // Old daemons' missing/mistyped words are a no-op. Indexed payloads
            // still replace the timeline even when malformed, so they fail closed.
            guard event["aligned_words"] != nil || event["words"] is [[String: Any]] else { return }
            let chunkStart = playbackChunkStartMilliseconds
            let chunkMs = (event["duration_ms"] as? NSNumber).map(\.intValue).flatMap { $0 > 0 ? $0 : nil }
            // An unmatched opening token must not inherit the player-spawn edge as its
            // acoustic onset. Decode already includes the file's leading silence; without
            // that evidence leave the prefix untimed rather than animate it in the gap.
            // Resume/seek envelopes start at the sliced audio, so retain an onset already
            // established for this chunk rather than move its opening words on each seek.
            let knownOpening = wordBoundaries.first.flatMap { row -> Int? in
                row.wordIndex == 0 && row.isInterpolated ? row.offsetMs : nil
            }
            let interpolationStart = knownOpening ?? playbackAmplitudeEnvelope.flatMap { envelope -> Int? in
                guard envelope.source == .decodedRMS,
                      let first = envelope.samples.firstIndex(where: { $0 > 0 }),
                      let envelopeStart = playbackAmplitudeStartedAt, let clockStart = playbackStartedAt
                else { return nil }
                return max(chunkStart, Int(((envelopeStart - clockStart) * 1000).rounded()) +
                           first * envelope.sampleIntervalMilliseconds)
            }
            wordBoundaries = TeleprompterBoundary.interpolated(
                TeleprompterBoundary.subtitleWords(event, chunkStartMs: chunkStart), text: statusText, startMs: interpolationStart,
                endMs: chunkMs.map { chunkStart + $0 } ?? (playbackLongReadID == nil ? playbackDurationMilliseconds : nil))
            if TeleprompterContentModel.words(text: statusText, wordBoundaries: wordBoundaries).contains(where: { $0.offsetMs != nil }) {
                playbackTimelineChunks[chunkStart] = (statusText, wordBoundaries)
            }
            if isShowingLongReadDocument, let start = longReadDocumentWordStart {
                longReadDocument?.record(chunkText: statusText, boundaries: wordBoundaries, wordStart: start)
            }

        case "queue":
            if let depth = event["depth"] as? Int {
                queueDepth = max(0, depth)
                refreshModelsBusy()
            }
            if let items = event["items"] as? [[String: Any]] {
                queueItems = items.compactMap { item in
                    guard let text = item["text"] as? String,
                          let voice = item["voice"] as? String,
                          let priority = item["priority"] as? String,
                          let isCurrent = item["is_current"] as? Bool
                    else { return nil }
                    let rawProgress = (item["progress"] as? Double)
                        ?? (item["progress"] as? Int).map(Double.init)
                        ?? 0
                    return QueueItemState(
                        text: text,
                        voice: voice,
                        priority: priority,
                        isCurrent: isCurrent,
                        progress: min(1, max(0, rawProgress))
                    )
                }
            } else if queueDepth == 0 {
                queueItems = []
            }

        case "audio_level":
            if let rms = event["rms"] as? Double {
                socketAudioLevel = Self.clampAudioLevel(rms)
                refreshAudioLevel()
                if mode == .recording, localRecordingLevel == nil {
                    appendRecordingWaveformSample()
                }
                noteFirstRecordingAudioLevelIfNeeded(socketRMS: socketAudioLevel)
            }

        case "health":
            var speechControlsChanged = false
            if let raw = event["tts_controls"] as? [String: Any], let controls = SpeechControlsState(controls: raw) {
                speechControlsChanged = speechControls != controls
                speechControls = controls
                if let id = timedOutSpeechPreviewID, controls.previewActive == false,
                   event["recording_state"] as? String == "idle", event["queue_depth"] as? Int == 0,
                   mode != .speaking {
                    speechRequestIDs[id] = nil
                    speechPending["preview"] = nil
                    timedOutSpeechPreviewID = nil
                    speechNotice = nil
                }
            }
            let status = ModelsSettingsState(healthEvent: event)
            modelsRecordingBusy = event["recording_state"] as? String != "idle"
            modelsRecordingReason = (event["recording_state"] as? String)
                .flatMap(ModelsSettingsState.busyReason(recordingState:))
            if let depth = event["queue_depth"] as? Int { queueDepth = max(0, depth) }
            modelsSettingsState = status
            refreshModelsBusy()
            remoteSTTConfigured = event["remote_stt_configured"] as? Bool
            // One repaint for new data; the root's follow-up identical health cannot rebuild again.
            if speechControlsChanged { onSpeechSettled?() }

        case "model_status":
            if isConnected, let modelStatus = event["model_status"] as? [String: Any] {
                let fresh = ModelsSettingsState(healthEvent: [
                    "type": "health", "recording_state": "idle", "model_status": modelStatus,
                ])
                modelsSettingsState = fresh.retainingPolishControls(from: modelsSettingsState)
                refreshModelsBusy()
            }

        case "command_mode":
            handleCommandModeEvent(event)

        case "mic_disconnected":
            // MICDROP2: say it now, and again in place of this dictation's paste confirmation so the
            // notice is the last thing the pill shows. Presentation only: the capture already ended.
            let notice = MicDisconnectFeedback.pill(atMs: (event["at_ms"] as? NSNumber)?.intValue ?? 0)
            pendingMicDisconnectNotice = notice
            showConfirmation(notice, duration: Self.micDisconnectNoticeSeconds)

        case "archive_metadata_updated":
            // F1: metadata written after the transcript was delivered (the ≈ spoken length). Refresh History's copy
            // of that entry only; this is not a transcript, so nothing is remembered, pasted or sent.
            guard let path = (event["recording_path"] as? String)?.trimmingCharacters(in: .whitespacesAndNewlines),
                  !path.isEmpty
            else { return }
            onHistoryArchiveChange?(path)

        case "vocabulary", "vocab_list", "stt_vocabulary":
            applyVocabularyEvent(event)

        case "clip_marker":
            if let id = event["marker_id"] as? String,
               let label = event["label"] as? String,
               let source = event["source"] as? String,
               let status = event["status"] as? String {
                activeClipMarker = ClipMarkerState(id: id, label: label, source: source, status: status)
                expandFromCollapse()
            }

        case "error":
            if event["source"] as? String == "seek" {
                if mode == .speaking { errorMessage = event["message"] as? String ?? "Seek failed" }
                else if isTeleprompterReadback { showConfirmation(event["message"] as? String ?? "Seek failed") }
                return
            }
            if showsReadingProcessingSpinner, event["source"] as? String != "playback" { return }
            let showDuringBarRecording = event["show_during_bar_recording"] as? Bool ?? false
            let shouldShowError = showDuringBarRecording || !barInitiatedRecording
            if shouldShowError {
                transcriptionTimeoutTask?.cancel()
                recordStartAckTimeoutTask?.cancel()
                pendingRecoveredTranscriptionPaste = false
                clearHistoryRetranscriptionRequest(removeSuppression: true)
            }
            // AIDEV-NOTE: NEVER reset barInitiatedRecording on error.
            // With multiple MCP clients, failing clients broadcast errors while
            // the successful client is still recording. Show error UI only if
            // we're not in an active bar-initiated recording.
            if showDuringBarRecording {
                barInitiatedRecording = false
                releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
                barInitiatedTimeout?.cancel()
                recordingIdleCleanupTask?.cancel()
                pendingIdleAfterAutoPasteCompletion = false
                clearRecordStartLateRecovery(clearPasteTarget: false)
                transcribingStartedAt = nil
                transcribingStatusText = nil
                frontmostAppOnRecordStart = nil
                recordStartInsertionHandler = nil
            }
            if shouldShowError {
                resetAudioLevels()
                mode = .error
                errorMessage = event["message"] as? String ?? "Unknown error"
                expandFromCollapse()
            }

        default:
            break
        }
    }

    private func applyVocabularyEvent(_ event: [String: Any]) {
        withVocabularyMirrorBatch { applyVocabularyEventFields(event) }
    }

    private func applyVocabularyEventFields(_ event: [String: Any]) {
        var appliedSnapshot = false
        let displayRows = (event["display_entries"] as? [[String: Any]])?
            .compactMap(STTDictionaryDisplayEntry.init(eventRow:))

        if let entries = event["entries"] as? [[String: Any]] {
            let preview = STTVocabularyPreview(
                updatedAt: event["updated_at"] as? String,
                entries: entries.compactMap { entry in
                    guard let canonical = entry["canonical"] as? String else { return nil }
                    return STTDictionaryEntry(
                        canonical: canonical,
                        variants: entry["variants"] as? [String] ?? []
                    )
                }
            )
            transcriptionVocabularyTerms = Self.normalizeVocabularyTerms(preview.promptTerms)
            transcriptionVocabularyAliases = Self.normalizeVocabularyAliases(preview.aliases)
            appliedSnapshot = true
        }

        if let promptTerms = event["prompt_terms"] as? [String] {
            transcriptionVocabularyTerms = Self.normalizeVocabularyTerms(promptTerms)
            appliedSnapshot = true
        }

        if let aliases = event["aliases"] as? [[String: Any]] {
            transcriptionVocabularyAliases = Self.normalizeVocabularyAliases(
                aliases.compactMap { alias in
                    guard let from = alias["from"] as? String,
                          let to = alias["to"] as? String
                    else { return nil }
                    return STTVocabularyAliasPreview(from: from, to: to)
                }
            )
            appliedSnapshot = true
        }

        if appliedSnapshot {
            transcriptionVocabularyDisplayEntries = displayRows
        } else {
            // No snapshot: reload from the file, keeping the newest bundled rows this event or an earlier reply
            // carried (a row-less event must not wipe them).
            if let displayRows { transcriptionVocabularyDisplayEntries = displayRows }
            refreshTranscriptionVocabulary()
        }
    }

