    private func finishPasteConfirmation(outcome: VoicePasteOutcome, text: String) {
        logDiagnostic("paste_confirmation", details: [
            "outcome": String(describing: outcome),
        ])
        switch outcome {
        case .insertedAtCursor:
            showConfirmation(text, duration: 5.0)
        case .pasted:
            showConfirmation(text, duration: 5.0)
        case let .failed(message):
            showConfirmation(Self.failureMessageWithRetryHint(message), duration: 4.0)
        }

        if pendingIdleAfterAutoPasteCompletion {
            pendingIdleAfterAutoPasteCompletion = false
            pendingRecoveredTranscriptionPaste = false
            historyRetranscriptionRequest.clear(removeSuppression: false)
            enterIdleState(clearQueue: false)
        }
    }

    private func showConfirmation(_ message: String, duration: TimeInterval = 1.5) {
        confirmationText = message
        DispatchQueue.main.asyncAfter(deadline: .now() + duration) { [weak self] in
            if self?.confirmationText == message {
                self?.confirmationText = nil
                self?.keepsPasteFlowEnvelope = false
            }
        }
    }

    private static func failureMessageWithRetryHint(_ message: String) -> String {
        if message == genericPasteFailureMessage {
            return pasteFailureRetryMessage
        }
        return message
    }

    private func sendIntent(
        command: IntentCommand,
        payload: [String: Any],
        trackPending: Bool = true
    ) {
        let id = UUID().uuidString
        var payloadWithID = payload
        payloadWithID["id"] = id
        if trackPending {
            // An early PTT release must not mask a failed record start.
            if command == .stop, pendingIntent?.command == .record {
                sendCommand?(payloadWithID)
                return
            }
            recordStartAckTimeoutTask?.cancel()
            pendingIntent = PendingIntent(id: id, command: command)
            if command == .record {
                scheduleRecordStartAckTimeout(id: id)
            }
        }
        sendCommand?(payloadWithID)
    }

    public func handleCommandDeliveryFailure(
        _ command: [String: Any],
        reason: String = "VoiceLayer is starting"
    ) {
        guard let commandName = command["cmd"] as? String,
              let intentCommand = IntentCommand(rawValue: commandName),
              let id = command["id"] as? String,
              !id.isEmpty
        else {
            return
        }

        handleEvent([
            "type": "ack",
            "command": intentCommand.rawValue,
            "outcome": "reject",
            "id": id,
            "reason": reason,
        ])
    }

    private func scheduleRecordStartAckTimeout(id: String) {
        let timeout = recordStartAckTimeout
        recordStartAckTimeoutTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: timeout)
            guard let self,
                  !Task.isCancelled,
                  pendingIntent?.id == id,
                  pendingIntent?.command == .record
            else {
                return
            }

            handleEvent([
                "type": "ack",
                "command": IntentCommand.record.rawValue,
                "outcome": IntentOutcome.reject.rawValue,
                "id": id,
                "reason": "VoiceLayer is starting",
            ])
        }
    }

    private func scheduleRecordStartLateRecovery() {
        canRecoverLateRecordStart = true
        recordStartLateRecoveryTask?.cancel()
        let window = recordStartLateRecoveryWindow
        recordStartLateRecoveryTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: window)
            guard let self, !Task.isCancelled, canRecoverLateRecordStart else { return }
            clearRecordStartLateRecovery(clearPasteTarget: true)
        }
    }

    private func clearRecordStartLateRecovery(clearPasteTarget: Bool) {
        canRecoverLateRecordStart = false
        recordStartLateRecoveryTask?.cancel()
        recordStartLateRecoveryTask = nil
        if clearPasteTarget {
            frontmostAppOnRecordStart = nil
            recordStartInsertionHandler = nil
        }
    }

    private func logDiagnostic(_ event: String, details: [String: String] = [:]) {
        diagnosticLogger?(event, details)
        if Self.shouldMirrorDiagnosticToControlLayer(event) {
            controlLayerEventWriter(event, details)
        }
    }

    private func logFirstRecordingAudioLevelIfNeeded(socketRMS: Double?) {
        guard mode == .recording,
              !didLogFirstRecordingAudioLevel,
              let socketRMS
        else { return }
        let firstAudioUptimeMs = currentRecordingUptimeMs()
        didLogFirstRecordingAudioLevel = true
        var details = [
            "firstAudioLevelUptimeMs": String(firstAudioUptimeMs),
            "socketRms": Self.formatAudioLevel(socketRMS),
        ]
        if let recordCommandUptimeMs {
            details["msSinceRecordCommand"] = String(max(0, firstAudioUptimeMs - recordCommandUptimeMs))
        }
        if let recordingStateUptimeMs {
            details["msSinceRecordingState"] = String(max(0, firstAudioUptimeMs - recordingStateUptimeMs))
        }
        logDiagnostic("recording_first_audio_level", details: details)
    }

    private func currentRecordingUptimeMs() -> Int {
        Int((recordingTimingClock() * 1000).rounded())
    }

    private static func formatAudioLevel(_ level: Double) -> String {
        String(format: "%.4f", level)
    }

    private static func shouldMirrorDiagnosticToControlLayer(_ event: String) -> Bool {
        event == "transcription_final" ||
            event == "repaste_requested" ||
            event == "copy_transcript" ||
            event.hasPrefix("paste_")
    }

    private func boolString(_ value: Bool) -> String {
        value ? "true" : "false"
    }

    private func notifyPanelLayoutChangedIfNeeded(_ changed: Bool) {
        guard changed else { return }
        DispatchQueue.main.async { [weak self] in
            self?.onPanelLayoutChange?()
        }
    }

    private func handleAckEvent(_ event: [String: Any]) {
        guard let ack = SocketAckEvent(event: event) else {
            return
        }

        onAckEvent?(ack)

        if ack.command == .setRecordingHold,
           let pendingRecordingHold,
           pendingRecordingHold.id == ack.id {
            if ack.outcome != .accept {
                isRecordingHoldEngaged = pendingRecordingHold.previous
            }
            self.pendingRecordingHold = nil
            return
        }

        if ack.command == .retranscribeRecording,
           historyRetranscriptionRequest.matchesIntent(id: ack.id) {
            let path = historyRetranscriptionRequest.currentPath()
            historyRetranscriptionRequest.acknowledgeIntent()
            if ack.outcome != .accept {
                historyRetranscriptionRequest.reject(path: path)
                showConfirmation(ack.reason ?? "Nothing to transcribe")
            }
            return
        }

        guard pendingIntent?.id == ack.id,
              pendingIntent?.command == ack.command
        else {
            return
        }

        recordStartAckTimeoutTask?.cancel()
        pendingIntent = nil

        if ack.command == .retranscribeLast {
            if ack.outcome == .accept {
                // The daemon rejects retranscription while any capture is active, so acceptance is
                // authoritative that an older remote ownership latch or shadow is now stale.
                releaseRemoteCaptureOwnership(preservingPossibleTranscript: false)
            } else {
                pendingRecoveredTranscriptionPaste = false
                showConfirmation(ack.reason ?? "Nothing to transcribe")
            }
            return
        }

        if ack.command == .retranscribeRecording, ack.outcome != .accept {
            clearHistoryRetranscriptionRequest(removeSuppression: true)
            showConfirmation(ack.reason ?? "Nothing to transcribe")
            return
        }

        guard ack.command == .record, ack.outcome == .reject else { return }

        let canRecoverLateRecording = ack.reason == "VoiceLayer is starting"
        barInitiatedRecording = false
        releaseRemoteCaptureOwnership(preservingPossibleTranscript: true)
        barInitiatedTimeout?.cancel()
        recordingIdleCleanupTask?.cancel()
        recordStartAckTimeoutTask?.cancel()
        keepsPasteFlowEnvelope = false
        if canRecoverLateRecording {
            scheduleRecordStartLateRecovery()
        } else {
            clearRecordStartLateRecovery(clearPasteTarget: true)
        }
        hotkeyPhase = .idle
        resetAudioLevels()
        mode = .error
        errorMessage = ack.reason ?? "Unable to start recording"
        onModeChange?(.error)
        expandFromCollapse()
    }

    private func handleCommandModeEvent(_ event: [String: Any]) {
        guard let phaseString = event["phase"] as? String,
              let phase = CommandModePhase(rawValue: phaseString),
              let operation = event["operation"] as? String else {
            return
        }

        commandModeState = CommandModeState(
            phase: phase,
            operation: operation,
            prompt: event["prompt"] as? String
        )
        expandFromCollapse()

        guard phase == .applying, let replacementText = event["replacement_text"] as? String else {
            return
        }

        guard let commandModeApplyHandler else { return }
        let result = commandModeApplyHandler(replacementText)

        switch result {
        case let .axVerified(message):
            commandModeState = CommandModeState(phase: .done, operation: operation, prompt: event["prompt"] as? String)
            showConfirmation(message)
        case let .clipboardFallback(message):
            commandModeState = CommandModeState(
                phase: .fallback,
                operation: operation,
                prompt: event["prompt"] as? String
            )
            showConfirmation(message)
        case let .failed(message):
            commandModeState = CommandModeState(phase: .error, operation: operation, prompt: event["prompt"] as? String)
            mode = .error
            errorMessage = message
        }
    }

    private static func capturePasteboardSnapshot() -> PasteboardSnapshot? {
        let pasteboard = NSPasteboard.general
        let items = pasteboard.pasteboardItems?.compactMap { item -> [String: Data]? in
            let values = item.types.reduce(into: [String: Data]()) { result, type in
                guard !type.rawValue.hasPrefix("dyn."),
                      !type.rawValue.hasPrefix("org.nspasteboard.")
                else {
                    return
                }
                if let data = item.data(forType: type) {
                    result[type.rawValue] = data
                }
            }
            return values.isEmpty ? nil : values
        } ?? []

        guard !items.isEmpty else { return nil }
        return PasteboardSnapshot(changeCount: pasteboard.changeCount, items: items)
    }

    private static func restorePasteboardSnapshot(_ snapshot: PasteboardSnapshot) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let items = snapshot.items.map { itemSnapshot -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in itemSnapshot {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        pasteboard.writeObjects(items)
        pasteboard.setData(Data(), forType: .voiceBarTransient)
        pasteboard.setData(Data(), forType: .voiceBarAutoGenerated)
    }
