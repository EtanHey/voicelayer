    /// The app supplies actual window/tab visibility. Event bursts coalesce once;
    /// there is no periodic poll, and visibility is checked again before any send.
    public var recognizerSettingsIsVisible: () -> Bool = { false }
    var recognizerStatusReadClock: () -> TimeInterval = { ProcessInfo.processInfo.systemUptime }
    /// Scheduling and time are separate: a due read may wait for the main actor.
    var scheduleRecognizerStatusRead: (TimeInterval, @escaping @MainActor () -> Void) -> (() -> Void) = { delay, read in
        let task = Task { @MainActor in
            do { try await Task.sleep(for: .seconds(max(0, delay))) } catch { return }
            guard !Task.isCancelled else { return }
            read()
        }
        return { task.cancel() }
    }
    private var lastRecognizerStatusRead: TimeInterval?
    private var cancelCoalescedRecognizerRead: (() -> Void)?
    public static let recognizerStatusReadMinimumInterval: TimeInterval = 1

    public func refreshRecognizerStatus() { requestRecognizerStatus(coalesce: true) }

    private func requestRecognizerStatus(coalesce: Bool) {
        guard isConnected, recognizerSettingsIsVisible(), let sendCommand else { return }
        let now = recognizerStatusReadClock()
        guard now.isFinite else { return }
        if let last = lastRecognizerStatusRead, now - last < Self.recognizerStatusReadMinimumInterval {
            guard coalesce, cancelCoalescedRecognizerRead == nil else { return }
            let delay = Self.recognizerStatusReadMinimumInterval - (now - last)
            cancelCoalescedRecognizerRead = scheduleRecognizerStatusRead(delay) { [weak self] in
                guard let self else { return }
                self.cancelCoalescedRecognizerRead = nil
                self.requestRecognizerStatus(coalesce: false)
            }
            return
        }
        cancelCoalescedRecognizerRead?()
        cancelCoalescedRecognizerRead = nil
        lastRecognizerStatusRead = now
        let id = UUID().uuidString
        recognizerRefreshID = id
        recognizerRebasableReadID = id
        sendCommand(["cmd": "get_recognizer_status", "id": id])
    }

    public func manageRecognizer(_ engine: RecognizerPickerEngine, action: RecognizerManagementAction) {
        guard isConnected, let sendCommand, recognizerPickerState.canManage(engine, action: action) else { return }
        // Load on the row that isn't selected means "use this one": the daemon loads it and unloads the other.
        if action == .load, recognizerPickerState.selected != engine { selectRecognizer(engine); return }
        if action == .download, recognizerDownloadID != nil { return }
        let id = UUID().uuidString
        var command: [String: Any] = ["cmd": action.command, "engine": engine.rawValue, "id": id]
        if action == .load || action == .unload { command["action"] = action.rawValue }
        if action == .cancelDownload {
            recognizerCancelID = id
        } else if action == .download {
            recognizerDownloadID = id; recognizerDownloadReplyID = id
            recognizerNotice = nil; onRecognizerStatusChange?()
        } else {
            recognizerSelectionID = id; recognizerSelectionReplyID = id
            recognizerPendingCommand = action.command; recognizerSelectionTarget = nil
            recognizerNotice = nil; onRecognizerStatusChange?()
        }
        sendCommand(command)
        if action != .cancelDownload { scheduleRecognizerTimeout(id, engine: engine) }
    }

