// T19b (L68): VoiceBar's History glyph, concept A "take loop": History's counter-clockwise loop with the take
// itself (three waveform bars) where the clock hands were. Design and pick: docs.local/2.4-lanes/c7/
// REPORT-SYMBOL-AUDIT.md (concept SVG `symbol-audit/concepts/A-take-loop.svg`, 24-unit grid). Its 1.9 round stroke
// is 1.75 here, which matches the system clock's weight at 44 pt.
//
// SF Symbols templates take filled outlines, not strokes, so the concept's strokes are outlined with CoreGraphics
// (round caps and joins) and unioned. The template carries one master, Regular-M (actool requires it and accepts
// it alone), so the glyph keeps one weight at every font weight; at the notch's 11-12 pt that is the point.
//
// Run from the repo root:  swift flow-bar/Symbols/tools/generate-history-take.swift
import CoreGraphics
import Foundation

/// Concept grid (24 units, y down) to template units. The template's cap height at Regular-M is 70.46 units (font
/// size 100); the real `clock.arrow.circlepath` is about 125 units wide there, so one grid unit is 5.2 template units.
let scale: CGFloat = 5.2
let strokeWidth: CGFloat = 1.75 * scale
/// The glyph's vertical centre sits on the cap height's midline, as SF Symbols' own glyphs do.
let capMidline: CGFloat = -70.46 / 2

func gridPath() -> [CGPath] {
    var strokes: [CGPath] = []
    // The loop: centre (12, 12), radius 8.5, from 195° (left, just above the arrow tip) clockwise on screen to 155°.
    let loop = CGMutablePath()
    loop.addArc(center: CGPoint(x: 12, y: 12), radius: 8.5,
                startAngle: 195 * .pi / 180, endAngle: 155 * .pi / 180, clockwise: false)
    strokes.append(loop)
    // The arrowhead at the loop's start, pointing back down-left (History's counter-clockwise turn).
    let head = CGMutablePath()
    head.move(to: CGPoint(x: 1.4, y: 7.6))
    head.addLine(to: CGPoint(x: 3.79, y: 10.1))
    head.addLine(to: CGPoint(x: 6.5, y: 8.1))
    strokes.append(head)
    // The take: three bars, the middle one tallest.
    for (x, top, bottom) in [(9.0, 10.2, 13.8), (12.0, 8.0, 16.0), (15.0, 9.6, 14.4)] as [(CGFloat, CGFloat, CGFloat)] {
        let bar = CGMutablePath()
        bar.move(to: CGPoint(x: x, y: top))
        bar.addLine(to: CGPoint(x: x, y: bottom))
        strokes.append(bar)
    }
    return strokes
}

var transform = CGAffineTransform(scaleX: scale, y: scale)
let outlines = gridPath().map {
    $0.copy(using: &transform)!.copy(strokingWithWidth: strokeWidth, lineCap: .round, lineJoin: .round, miterLimit: 10)
}
var glyph = outlines[0]
for outline in outlines.dropFirst() { glyph = glyph.union(outline) }
// Left side bearing 0 at the ink; vertical centre on the cap midline.
let box = glyph.boundingBoxOfPath
var place = CGAffineTransform(translationX: -box.minX, y: capMidline - box.midY)
glyph = glyph.copy(using: &place)!
let width = glyph.boundingBoxOfPath.width

func fmt(_ v: CGFloat) -> String {
    let s = String(format: "%.3f", Double(v))
    return s.hasPrefix("-0.000") ? "0.000" : s
}

var data = ""
glyph.applyWithBlock { element in
    let p = element.pointee.points
    switch element.pointee.type {
    case .moveToPoint: data += "M\(fmt(p[0].x)) \(fmt(p[0].y))"
    case .addLineToPoint: data += "L\(fmt(p[0].x)) \(fmt(p[0].y))"
    case .addQuadCurveToPoint: data += "Q\(fmt(p[0].x)) \(fmt(p[0].y)) \(fmt(p[1].x)) \(fmt(p[1].y))"
    case .addCurveToPoint:
        data += "C\(fmt(p[0].x)) \(fmt(p[0].y)) \(fmt(p[1].x)) \(fmt(p[1].y)) \(fmt(p[2].x)) \(fmt(p[2].y))"
    case .closeSubpath: data += "Z"
    @unknown default: break
    }
}

